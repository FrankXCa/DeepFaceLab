def build_manifest(
    runtime_id: str,
    identity: PythonAsset,
    inventory: PythonLicenseInventory,
    lock: Lock,
    bootstrap_sha256: str,
    baseline: dict[str, set[str]],
    tree_inventory: dict,
    checks: list[Check],
    started_utc: datetime,
    duration_seconds: float,
    notes: list[str],
    torch_hardware: dict | None = None,
    normalizations: list[dict] | None = None,
    console_scripts: dict[str, str] | None = None,
) -> dict:
    canonical = {
        "artifacts": {
            "python_archive": {
                "filename": identity.filename,
                "sha256": identity.sha256,
                "url": identity.source_url,
            },
            **{
                wheel.name: {
                    "classification": wheel.classification,
                    "filename": wheel.filename,
                    "sha256": wheel.sha256,
                    "source": wheel.source,
                    "url": wheel.url,
                }
                for wheel in sorted(lock.wheels, key=lambda w: w.name)
            },
        },
        "builder": {"contract": BUILDER_CONTRACT, "version": BUILDER_VERSION},
        # Deterministic semantic record of the console-script entry points
        # (name -> "module:function") that pip would have exposed as
        # Scripts/*.exe launchers; the launcher binaries themselves are NOT
        # shipped (see launcher contract), entry points are invoked via the
        # runtime's own interpreter.
        "console_scripts": dict(sorted((console_scripts or {}).items())),
        "installed_tree": tree_inventory,
        # Authoritative installed-tree integrity digest (actual file bytes);
        # this value anchors the runtime ID.
        "installed_tree_inventory_sha256": tree_inventory.get("inventory_sha256", ""),
        "interpreter_baseline": {name: sorted(versions) for name, versions in sorted(baseline.items())},
        "lock": {
            "filename": lock.lock_filename,
            "generator_sha256": lock.generator_sha256,
            "input_hashes": dict(sorted(lock.input_hashes.items())),
            "input_identity_sha256": lock.input_identity_sha256,
            "resolver": lock.resolver,
            "resolver_config_sha256": lock.resolver_config_sha256,
            "schema": lock.schema,
            "sha256": lock.lock_sha256,
        },
        "package_set": dict(sorted(lock.package_set.items())),
        "python": identity.canonical(),
        "python_license_inventory": {
            "entries": [
                {
                    "archive_path": entry.archive_path,
                    "path": entry.installed_path,
                    "sha256": entry.sha256,
                }
                for entry in inventory.entries
            ],
            "sha256": inventory.inventory_sha256,
        },
        "runtime_id": runtime_id,
        "runtime_id_inputs": {
            "bootstrap_path": BOOTSTRAP_RELATIVE,
            "bootstrap_sha256": bootstrap_sha256,
            "lock_sha256": lock.lock_sha256,
            "python_license_inventory_sha256": inventory.inventory_sha256,
            "python_sha256": identity.sha256,
            "variant": lock.variant,
        },
        "schema": MANIFEST_SCHEMA,
        "target": {
            "gui": lock.gui,
            "platform": lock.target_platform,
            "python": lock.target_python,
            "torch_backend": lock.torch_backend,
            "torch_version": lock.package_set.get("torch", ""),
            "wheel_platform": lock.wheel_platform,
        },
        "variant": lock.variant,
        # Canonical verification must be deterministic: the torch build line is
        # verified regardless of whether this host has a physical GPU, so the
        # hardware-sensitive torch_probe state (PASS vs ENVIRONMENTALLY_LIMITED)
        # is collapsed to the deterministic "VERIFIED" for CUDA variants. The
        # raw hardware state is preserved in operational (torch_hardware) so a
        # CUDA host and a non-CUDA host produce the SAME canonical manifest.
        "verification": {
            check.name: (
                "VERIFIED"
                if check.name == "torch_probe"
                and lock.torch_backend == "cu130"
                and check.code in ("PASS", "ENVIRONMENTALLY_LIMITED")
                else check.code
            )
            for check in checks
        },
    }
    operational = {
        "build_duration_seconds": round(duration_seconds, 2),
        "built_utc": started_utc.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "notes": list(notes),
    }
    if torch_hardware is not None:
        operational["torch_hardware"] = torch_hardware
    if normalizations:
        operational["normalizations"] = list(normalizations)
    return {"canonical": canonical, "operational": operational, "schema": MANIFEST_SCHEMA}


def write_manifest(manifest_path: Path, manifest: dict) -> None:
    text = json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=True) + "\n"
    scan_privacy(text, MANIFEST_NAME)
    manifest_path.write_text(text, encoding="utf-8", newline="\n")


def read_manifest(manifest_path: Path) -> dict:
    with manifest_path.open("r", encoding="utf-8") as stream:
        return json.load(stream)


