def _is_private_ip(ip: str) -> bool:
    octets = tuple(int(part) for part in ip.split("."))
    if any(octet > 255 for octet in octets):
        return False
    return (
        octets[0] == 10
        or octets[0] == 127
        or octets[0] == 0
        or octets[0] == 255
        or (octets[0] == 192 and octets[1] == 168)
        or (octets[0] == 172 and 16 <= octets[1] <= 31)
        or (octets[0] == 169 and octets[1] == 254)
    )


def privacy_violations(text: str) -> list[str]:
    """Return stable labels for any privacy rule the text violates."""
    violations: list[str] = []
    for pattern, label in PRIVACY_RULES:
        if pattern.search(text):
            violations.append(label)
    for match in IPV4_RE.findall(text):
        if _is_private_ip(match):
            violations.append(f"private IP {match}")
    return violations


def scan_privacy(text: str, where: str) -> None:
    violations = privacy_violations(text)
    if violations:
        raise BuilderError("privacy", f"privacy rule violation in {where}: {violations}")


