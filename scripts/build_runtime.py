def verify_runtime(
    runtime_dir: Path,
    lock: Lock,
    identity: PythonAsset,
    inventory: PythonLicenseInventory,
    bootstrap_sha256: str,
) -> list[Check]:
    """Verify a runtime directory against the CURRENT Commit-1 authority.

    Trust model (module docstring, "Manifest trust boundary"):

    * Class A identity fields are verified against the CURRENT Commit-1
      repository inputs handed in by the caller (``lock`` / ``identity`` /
      ``inventory``), the current bootstrap SHA-256 (``bootstrap_sha256``,
      i.e. the current scripts/runtime_entry.py), and this builder's
      contract:
        - builder contract + version (deterministic builder contract)
        - bootstrap sha256
        - variant
        - pinned Python asset identity (current runtime-python.json)
        - license-inventory identity (current runtime-python-licenses.json)
        - lock identity: schema / filename / SHA-256 / resolver /
          resolver-config / generator / input hashes (current
          runtime-lock.json of this variant) + target contract fields
        - package set (current lock)
        - artifact entries (classification / filename / SHA-256 / source /
          URL for every locked wheel plus the Python archive; the manifest
          must list exactly the current lock's artifacts - no missing,
          extra or forged records)
      The EXPECTED runtime ID is computed from those current inputs plus
      the installed-tree integrity digest recomputed from the ACTUAL bytes
      of the tree, and must equal BOTH the directory name and the
      manifest's recorded runtime ID. The manifest's self-reported identity
      blocks are evidence, never authority: a manifest that claims old
      lock / Python / artifact identities fails even when the package
      versions are unchanged.
    * Verification scope is filesystem-derived: installed distributions
      are re-enumerated from the tree (dist-info AND egg-info, duplicate
      normalized names rejected, exact normalized key set required against
      the current lock plus the recorded interpreter baseline), and RECORD
      payload integrity is byte-verified for EVERY distribution directory
      physically present. The manifest's ``installed_tree`` block is
      compared as a consistency record only - it can never shrink the
      scope.
    * Payload integrity is anchored to the runtime ID: the tree digest
      hashes actual file bytes (never the RECORD's claimed hashes), so
      editing a RECORD cannot hide a payload edit, and any planted or
      deleted file changes the digest and the expected ID.
    """
    runtime_dir = Path(runtime_dir)
    manifest_path = runtime_dir / MANIFEST_NAME
    if not manifest_path.is_file():
        return [Check("manifest", "MISSING_MANIFEST", MANIFEST_NAME)]
    manifest = read_manifest(manifest_path)
    if manifest.get("schema") != MANIFEST_SCHEMA:
        return [Check("manifest", "SCHEMA_MISMATCH", str(manifest.get("schema")))]
    canonical = manifest.get("canonical", {})
    if canonical.get("schema") != MANIFEST_SCHEMA:
        return [Check("manifest", "SCHEMA_MISMATCH", "canonical schema mismatch")]
    scan_privacy(manifest_path.read_text(encoding="utf-8"), MANIFEST_NAME)
    checks: list[Check] = [Check("manifest_privacy", "PASS")]

    builder_block = canonical.get("builder", {})
    if (
        builder_block.get("contract") != BUILDER_CONTRACT
        or builder_block.get("version") != BUILDER_VERSION
    ):
        return [Check("builder_contract", "MISMATCH", str(builder_block))]
    checks.append(Check("builder_contract", "PASS"))

    rii = canonical.get("runtime_id_inputs", {})
    if (
        rii.get("bootstrap_path") != BOOTSTRAP_RELATIVE
        or rii.get("bootstrap_sha256") != bootstrap_sha256
    ):
        return [
            Check(
                "bootstrap",
                "MISMATCH",
                "recorded bootstrap identity deviates from the current runtime_entry.py",
            )
        ]
    checks.append(Check("bootstrap", "PASS"))

    if canonical.get("variant") != lock.variant:
        return [Check("variant", "MISMATCH", f"{canonical.get('variant')} != {lock.variant}")]
    checks.append(Check("variant", "PASS", lock.variant))

    python_block = canonical.get("python", {})
    try:
        recorded = PythonAsset(**{k: python_block.get(k, "") for k in PythonAsset.__dataclass_fields__})
    except TypeError:
        return [Check("python", "MISMATCH", "python block malformed")]
    if recorded != identity:
        return [
            Check(
                "python",
                "MISMATCH",
                "recorded Python identity deviates from the current runtime-python.json",
            )
        ]
    if not (runtime_dir / "python.exe").is_file():
        return [Check("python", "MISSING_INTERPRETER", "python.exe")]
    checks.append(Check("python", "PASS", identity.filename))

    license_checks = check_python_license_tree(runtime_dir, inventory, identity)
    checks.append(license_checks[0])

    # -- License-inventory identity: the manifest's recorded inventory must
    # equal the CURRENT runtime-python-licenses.json inventory exactly.
    plinv = canonical.get("python_license_inventory", {})
    expected_plinv = {
        "entries": [
            {"archive_path": e.archive_path, "path": e.installed_path, "sha256": e.sha256}
            for e in inventory.entries
        ],
        "sha256": inventory.inventory_sha256,
    }
    checks.append(
        Check(
            "license_inventory_identity",
            "PASS" if plinv == expected_plinv else "MISMATCH",
            "recorded license inventory deviates from the current runtime-python-licenses.json"
            if plinv != expected_plinv
            else "",
        )
    )

    # -- Lock authority: every identity field of the manifest's lock block
    # (and the target contract) must equal the CURRENT Commit-1 lock of
    # this variant.
    lock_block = canonical.get("lock", {})
    target_block = canonical.get("target", {})
    lock_problems: list[str] = []
    for key, want in (
        ("schema", lock.schema),
        ("filename", lock.lock_filename),
        ("sha256", lock.lock_sha256),
        ("resolver", lock.resolver),
        ("resolver_config_sha256", lock.resolver_config_sha256),
        ("generator_sha256", lock.generator_sha256),
        ("input_identity_sha256", lock.input_identity_sha256),
    ):
        if lock_block.get(key) != want:
            lock_problems.append(f"lock.{key}")
    if dict(sorted(lock_block.get("input_hashes", {}).items())) != dict(
        sorted(lock.input_hashes.items())
    ):
        lock_problems.append("lock.input_hashes")
    for key, want in (
        ("gui", lock.gui),
        ("platform", lock.target_platform),
        ("python", lock.target_python),
        ("torch_backend", lock.torch_backend),
        ("wheel_platform", lock.wheel_platform),
    ):
        if target_block.get(key) != want:
            lock_problems.append(f"target.{key}")
    checks.append(
        Check(
            "lock_authority",
            "PASS" if not lock_problems else "MISMATCH",
            "; ".join(lock_problems[:6]),
        )
    )

    if canonical.get("package_set", {}) != lock.package_set:
        return [Check("package_set", "MISMATCH", "manifest package set deviates from the current lock")]
    checks.append(Check("package_set", "PASS", f"{len(lock.package_set)} locked distributions"))

    # -- Artifact authority: the manifest's artifact map must equal the
    # current lock's artifact records EXACTLY (no missing/extra/forged
    # records; url and source compared, not just filename/hash).
    wheel_by_name = {w.name: w for w in lock.wheels}
    artifacts = canonical.get("artifacts", {})
    artifact_problems: list[str] = []
    python_archive = artifacts.get("python_archive", {})
    if (
        python_archive.get("filename") != identity.filename
        or python_archive.get("sha256") != identity.sha256
        or python_archive.get("url") != identity.source_url
    ):
        artifact_problems.append("python_archive")
    wheel_records = {k: v for k, v in artifacts.items() if k != "python_archive"}
    if set(wheel_records) != set(wheel_by_name):
        artifact_problems.append(
            "artifact wheel set (missing="
            + ",".join(sorted(set(wheel_by_name) - set(wheel_records))[:3])
            + " extra="
            + ",".join(sorted(set(wheel_records) - set(wheel_by_name))[:3])
            + ")"
        )
    else:
        for name in sorted(wheel_by_name):
            spec = wheel_by_name[name]
            rec = wheel_records[name]
            if not isinstance(rec, dict):
                artifact_problems.append(name)
                continue
            if (
                rec.get("classification") != spec.classification
                or rec.get("filename") != spec.filename
                or rec.get("sha256") != spec.sha256
                or rec.get("source") != spec.source
                or rec.get("url") != spec.url
            ):
                artifact_problems.append(name)
    checks.append(
        Check(
            "artifact_authority",
            "PASS" if not artifact_problems else "MISMATCH",
            "; ".join(artifact_problems[:6]),
        )
    )

    recorded_set = canonical.get("package_set", {})
    if recorded_set != lock.package_set:
        return [Check("package_set", "MISMATCH", "manifest package set deviates from the lock")]
    checks.append(Check("package_set", "PASS", f"{len(lock.package_set)} locked distributions"))

    # -- Installed distributions: re-enumerated from the ACTUAL tree
    # (dist-info AND egg-info); duplicate normalized names are rejected;
    # the exact normalized key set must equal the current lock's package
    # set plus the recorded interpreter baseline.
    dist_map, duplicates = enumerate_tree_distributions(runtime_dir)
    baseline_block = canonical.get("interpreter_baseline", {})
    expected_full: dict[str, set[str]] = {
        locklib.normalized_name(name): set(versions) for name, versions in baseline_block.items()
    }
    for name, version in lock.package_set.items():
        expected_full.setdefault(locklib.normalized_name(name), set()).add(version)
    actual_versions: dict[str, set[str]] = {
        name: {ver for ver, _dir in entries} for name, entries in dist_map.items()
    }
    dist_problems: list[str] = []
    for name in sorted(set(actual_versions) | set(expected_full)):
        have = actual_versions.get(name, set())
        want = expected_full.get(name, set())
        if have != want:
            dist_problems.append(
                f"{name}: installed={sorted(have) or 'absent'} expected={sorted(want) or 'absent'}"
            )
    if duplicates:
        dist_problems.append("duplicate distributions: " + ", ".join(duplicates[:4]))
    total_dists = sum(len(entries) for entries in dist_map.values())
    checks.append(
        Check(
            "installed_distributions",
            "PASS" if not dist_problems else "MISMATCH",
            f"{total_dists} distributions re-enumerated"
            if not dist_problems
            else "; ".join(dist_problems[:4]),
        )
    )
    variant_checks = verify_variant_contract(actual_versions, lock)
    checks.append(variant_checks[0])

    # -- Console-script entry points: RECOMPUTED from the installed
    # metadata (every installed dist-info / egg-info entry_points.txt
    # [console_scripts] section) and required to equal the canonical
    # manifest's console_scripts EXACTLY. The manifest field is evidence,
    # not authority: a manifest tamper alone fails this check, and an
    # installed entry_points.txt tamper fails it AND the runtime-ID check
    # (the tree digest covers the metadata bytes).
    actual_console_scripts = collect_console_scripts(runtime_dir)
    manifest_console_scripts = canonical.get("console_scripts", {})
    if not isinstance(manifest_console_scripts, dict):
        manifest_console_scripts = {}
    console_problems: list[str] = []
    if actual_console_scripts != manifest_console_scripts:
        missing = sorted(set(manifest_console_scripts) - set(actual_console_scripts))[:3]
        extra = sorted(set(actual_console_scripts) - set(manifest_console_scripts))[:3]
        changed = sorted(
            k
            for k in set(actual_console_scripts) & set(manifest_console_scripts)
            if actual_console_scripts[k] != manifest_console_scripts[k]
        )[:3]
        console_problems.append(
            "console-script entry points deviate from the manifest: "
            f"missing={','.join(missing) or '-'} "
            f"extra={','.join(extra) or '-'} "
            f"changed={','.join(changed) or '-'}"
        )
    checks.append(
        Check(
            "console_scripts",
            "PASS" if not console_problems else "MISMATCH",
            f"{len(actual_console_scripts)} entry points re-derived from the installed metadata"
            if not console_problems
            else "; ".join(console_problems[:3]),
        )
    )

    # -- Runtime ID authority: expected ID = f(CURRENT inputs, tree digest
    # recomputed from the ACTUAL bytes) must equal the directory name AND
    # the manifest's recorded runtime ID.
    tree_digest = compute_installed_tree_digest(runtime_dir)
    expected_id = compute_runtime_id(bootstrap_sha256, identity, inventory, lock, tree_digest)
    id_problems: list[str] = []
    if runtime_dir.name != expected_id:
        id_problems.append("directory name")
    if canonical.get("runtime_id") != expected_id:
        id_problems.append("manifest runtime_id")
    checks.append(
        Check(
            "runtime_id",
            "PASS" if not id_problems else "MISMATCH",
            (
                "does not match the expected runtime ID derived from the current "
                f"Commit-1 inputs + recomputed tree digest ({'; '.join(id_problems)})"
                if id_problems
                else f"bound to current inputs + tree digest {tree_digest[:16]}..."
            ),
        )
    )

    # -- installed_tree: the manifest's inventory is a CONSISTENCY record -
    # its distribution block must cover exactly the current lock's names and
    # its per-distribution digests must match the actual tree. (Baseline
    # distributions such as pip are recorded in interpreter_baseline, not in
    # installed_tree.distributions; their presence is checked there and in
    # installed_distributions.)
    expected_tree = canonical.get("installed_tree", {})
    tree_problems: list[str] = []
    manifest_dists = expected_tree.get("distributions", {})
    locked_norm = {locklib.normalized_name(n) for n in lock.package_set}
    manifest_names = {locklib.normalized_name(n) for n in manifest_dists}
    if manifest_names != locked_norm:
        tree_problems.append(
            "distribution coverage (missing="
            + ",".join(sorted(locked_norm - manifest_names)[:3])
            + " extra="
            + ",".join(sorted(manifest_names - locked_norm)[:3])
            + ")"
        )
    for name, record in sorted(expected_tree.get("distributions", {}).items()):
        if not isinstance(record, dict):
            tree_problems.append(f"{name}: malformed record")
            continue
        norm = locklib.normalized_name(name)
        entries = dist_map.get(norm, [])
        present_dirs = {d for _ver, d in entries}
        dist_dir = runtime_dir / record.get("dist_info", "")
        if not entries or dist_dir not in present_dirs:
            tree_problems.append(f"{name}: dist_info path not present in tree")
            continue
        metadata = dist_dir / "METADATA"
        if not metadata.is_file() or locklib.sha256_file_raw(metadata) != record.get("metadata_sha256", ""):
            tree_problems.append(f"{name}: METADATA digest")
            continue
        record_file = dist_dir / "RECORD"
        if record_file.is_file() and normalized_record_sha256(record_file) != record.get("record_sha256", ""):
            tree_problems.append(f"{name}: RECORD digest")
            continue
    for name, digest in sorted(expected_tree.get("root_files", {}).items()):
        if name == MANIFEST_NAME:
            continue
        target = runtime_dir / name
        if not target.is_file() or locklib.sha256_file_raw(target) != digest:
            tree_problems.append(f"root {name}")
    if expected_tree.get("inventory_sha256", "") != tree_digest:
        tree_problems.append("inventory_sha256 deviates from the recomputed tree digest")
    checks.append(
        Check(
            "installed_tree",
            "PASS" if not tree_problems else "MISMATCH",
            "; ".join(tree_problems[:4]),
        )
    )

    # -- Byte-level payload integrity per RECORD semantics. Scope = EVERY
    # distribution directory physically present in the tree (filesystem-
    # derived; the manifest cannot shrink it). The on-disk RECORD is
    # authoritative for these per-file byte checks only because the
    # runtime-ID check above anchored it via the tree digest.
    site_packages = runtime_dir / "Lib" / "site-packages"
    dist_dirs = sorted(
        {d for entries in dist_map.values() for _ver, d in entries},
        key=str,
    )
    integrity_violations = verify_record_integrity(runtime_dir, site_packages, dist_dirs)
    checks.append(
        Check(
            "record_integrity",
            "PASS" if not integrity_violations else "MISMATCH",
            f"{len(dist_dirs)} distributions byte-verified"
            if not integrity_violations
            else "; ".join(integrity_violations[:4]),
        )
    )

    prohibited = scan_prohibited(runtime_dir)
    checks.append(Check("prohibited_cache", "PASS" if not prohibited else "PRESENT", "; ".join(prohibited[:3])))

    baseline_problems: list[str] = []
    if not baseline_block:
        baseline_problems.append("interpreter baseline missing from manifest")
    else:
        for name, versions in sorted(baseline_block.items()):
            have = actual_versions.get(locklib.normalized_name(name), set())
            if not set(versions) & have:
                baseline_problems.append(f"{name}: baseline version {sorted(versions)} not present in tree")
    checks.append(
        Check(
            "interpreter_baseline",
            "PASS" if not baseline_problems else "MISMATCH",
            "; ".join(baseline_problems[:3]),
        )
    )

    return checks


