def validate_variant(variant: str) -> None:
    if variant not in VARIANTS:
        raise BuilderError(
            "variant",
            f"unknown or invalid variant {variant!r}; exactly one of "
            f"{', '.join(VARIANTS)} must be given",
        )


def load_python_identity(repo_root: Path = REPO_ROOT) -> PythonAsset:
    path = repo_root / "runtime-python.json"
    if not path.is_file():
        raise BuilderError("identity", "missing runtime-python.json")
    identity = locklib.load_json(path)
    if identity.get("schema_version") != 1:
        raise BuilderError("identity", "unsupported runtime-python.json schema_version")
    archive = identity.get("archive", {})
    asset = PythonAsset(
        project=identity.get("project", ""),
        implementation=identity.get("implementation", ""),
        version=identity.get("version", ""),
        release=archive.get("release", ""),
        target_triple=archive.get("target_triple", ""),
        cpu_baseline=archive.get("cpu_baseline", ""),
        flavor=archive.get("flavor", ""),
        filename=archive.get("filename", ""),
        source_url=archive.get("source_url", ""),
        sha256=archive.get("sha256", ""),
    )
    for field_name in PINNED_PYTHON:
        if getattr(asset, field_name) != PINNED_PYTHON[field_name]:
            raise BuilderError(
                "identity",
                f"Python asset identity deviates from the pinned Commit-1 asset "
                f"({field_name}): expected {PINNED_PYTHON[field_name]!r}, "
                f"got {getattr(asset, field_name)!r}",
            )
    return asset


def load_license_inventory(
    repo_root: Path, identity: PythonAsset
) -> PythonLicenseInventory:
    path = repo_root / "runtime-python-licenses.json"
    if not path.is_file():
        raise BuilderError("identity", "missing runtime-python-licenses.json")
    inventory = locklib.load_json(path)
    if inventory.get("schema") != LICENSE_INVENTORY_SCHEMA:
        raise BuilderError("identity", "unsupported Python license inventory schema")
    source = inventory.get("source_archive", {})
    for field_name, expected in (
        ("filename", identity.filename),
        ("sha256", identity.sha256),
        ("source_url", identity.source_url),
        ("release", identity.release),
        ("target_triple", identity.target_triple),
        ("cpu_baseline", identity.cpu_baseline),
        ("flavor", identity.flavor),
    ):
        if source.get(field_name) != expected:
            raise BuilderError(
                "identity",
                f"license inventory source identity mismatch ({field_name})",
            )
    entries_raw = inventory.get("entries")
    if not isinstance(entries_raw, list) or not entries_raw:
        raise BuilderError("identity", "Python license inventory is empty")
    entries: list[LicenseEntry] = []
    previous = ""
    for raw in entries_raw:
        archive_path = raw.get("path", "")
        if not archive_path.startswith(PYTHON_ARCHIVE_ROOT + "/"):
            raise BuilderError("identity", f"license entry outside {PYTHON_ARCHIVE_ROOT}/: {archive_path}")
        installed_path = archive_path[len(PYTHON_ARCHIVE_ROOT) + 1 :]
        key = archive_path.casefold()
        if key < previous:
            raise BuilderError("identity", "license inventory is not deterministically sorted")
        previous = key
        entries.append(
            LicenseEntry(
                archive_path=archive_path,
                installed_path=installed_path,
                sha256=raw.get("sha256", ""),
                source_archive_filename=raw.get("source_archive_filename", ""),
                source_archive_sha256=raw.get("source_archive_sha256", ""),
            )
        )
        if not HASH_RE.fullmatch(entries[-1].sha256):
            raise BuilderError("identity", f"invalid license SHA-256: {archive_path}")
        if entries[-1].source_archive_filename != identity.filename:
            raise BuilderError("identity", f"license source filename mismatch: {archive_path}")
        if entries[-1].source_archive_sha256 != identity.sha256:
            raise BuilderError("identity", f"license source SHA-256 mismatch: {archive_path}")
    expected_hash = locklib.sha256_bytes(locklib.canonical_json(entries_raw).encode("ascii"))
    if inventory.get("inventory_sha256") != expected_hash:
        raise BuilderError("identity", "license inventory content hash mismatch")
    return PythonLicenseInventory(
        schema=LICENSE_INVENTORY_SCHEMA,
        inventory_sha256=inventory["inventory_sha256"],
        entries=tuple(entries),
    )


def _iter_header_lines(lock_path: Path) -> list[str]:
    return [line for line in lock_path.read_text(encoding="utf-8").splitlines() if line.startswith("# ")]


def load_lock(repo_root: Path, config: dict, variant: str) -> Lock:
    """Load and re-verify the exact Commit-1 artifact lock for a variant."""
    lock_path = repo_root / f"requirements-lock-{variant}.txt"
    if not lock_path.is_file():
        raise BuilderError("lock", f"missing artifact lock: {lock_path.name}")
    text = lock_path.read_text(encoding="utf-8")
    if "--only-binary=:all:" not in text or "--require-hashes" not in text:
        raise BuilderError("lock", f"install contract missing from {lock_path.name}")
    if locklib.PRIVATE_PATH_RE.search(text):
        raise BuilderError("privacy", f"private/local path leaked into {lock_path.name}")
    violations = privacy_violations(text)
    if violations:
        raise BuilderError("privacy", f"privacy rule violation in {lock_path.name}: {violations}")

    headers, entries = locklib.parse_lock(lock_path)
    if headers.get("schema") != LOCK_SCHEMA:
        raise BuilderError("lock", f"schema header mismatch in {lock_path.name}")
    if headers.get("variant") != variant:
        raise BuilderError("lock", f"variant header mismatch in {lock_path.name}")
    resolver = f"uv {config['resolver']['version']}"
    if headers.get("resolver") != resolver:
        raise BuilderError("lock", f"resolver header mismatch in {lock_path.name}")

    config_hash = locklib.sha256_file_text_canonical(repo_root / "runtime-lock.json")
    generator_hash = locklib.sha256_file_text_canonical(
        repo_root / "scripts" / "generate_runtime_locks.py"
    )
    if headers.get("resolver-config-sha256") != config_hash:
        raise BuilderError("lock", f"stale resolver config hash in {lock_path.name}")
    if headers.get("generator-sha256") != generator_hash:
        raise BuilderError("lock", f"stale generator hash in {lock_path.name}")

    variant_config = config["variants"][variant]
    _direct, input_paths = locklib.read_requirement_inputs(
        [str(name) for name in variant_config["inputs"]]
    )
    input_hashes = locklib.input_hashes(input_paths)
    expected_input_identity = locklib.sha256_bytes(locklib.canonical_json(input_hashes).encode("ascii"))

    header_inputs: dict[str, str] = {}
    for line in _iter_header_lines(lock_path):
        body = line[2:]
        if body.startswith("input-sha256: "):
            file_name, digest = body[len("input-sha256: ") :].split("=", 1)
            header_inputs[file_name] = digest
    if header_inputs != input_hashes:
        raise BuilderError("lock", f"stale direct input hashes in {lock_path.name}")

    required_fields = {
        "classification", "compatibility_tags", "filename", "input_hashes",
        "input_identity_sha256", "name", "resolver", "resolver_config_sha256",
        "sha256", "source", "target_platform", "target_python", "url",
        "variant", "version",
    }
    expected_versions = locklib.expected_versions(config, variant)
    names: list[str] = []
    wheels: list[WheelArtifact] = []
    for entry in entries:
        if set(entry) != required_fields:
            raise BuilderError("lock", f"artifact schema mismatch in {lock_path.name}")
        name = entry["name"]
        names.append(name)
        if entry["classification"] != (
            "direct" if name in {locklib.normalized_name(k) for k in _direct} else "transitive"
        ):
            raise BuilderError("lock", f"classification mismatch for {name}")
        if entry["input_hashes"] != input_hashes or entry["input_identity_sha256"] != expected_input_identity:
            raise BuilderError("lock", f"input identity mismatch for {name}")
        if entry["resolver_config_sha256"] != config_hash:
            raise BuilderError("lock", f"config identity mismatch for {name}")
        if entry["variant"] != variant or entry["target_python"] != config["target"]["python"]:
            raise BuilderError("lock", f"target identity mismatch for {name}")
        if not entry["filename"].endswith(".whl") or locklib.wheel_score(entry["filename"]) is None:
            raise BuilderError("lock", f"non-wheel/incompatible artifact for {name}")
        if not HASH_RE.fullmatch(entry["sha256"]):
            raise BuilderError("lock", f"invalid artifact SHA-256 for {name}")
        url_name = PurePosixPath(urllib.parse.urlsplit(entry["url"]).path).name
        if url_name != urllib.parse.quote(entry["filename"], safe="-_.") and urllib.parse.unquote(url_name) != entry["filename"]:
            raise BuilderError("lock", f"artifact URL/filename mismatch for {name}")
        host = urllib.parse.urlsplit(entry["url"]).hostname or ""
        if name == "torch":
            if host not in {"download.pytorch.org", "download-r2.pytorch.org"}:
                raise BuilderError("lock", f"unofficial torch source in {lock_path.name}")
        elif host != "files.pythonhosted.org" or entry["source"] != "https://pypi.org/simple":
            raise BuilderError("lock", f"non-PyPI ordinary artifact for {name}")
        wheels.append(
            WheelArtifact(
                name=name,
                version=entry["version"],
                classification=entry["classification"],
                filename=entry["filename"],
                url=entry["url"],
                sha256=entry["sha256"],
                source=entry["source"],
                compatibility_tags=tuple(entry["compatibility_tags"]),
                input_identity_sha256=entry["input_identity_sha256"],
                resolver=entry["resolver"],
                resolver_config_sha256=entry["resolver_config_sha256"],
            )
        )

    if len(names) != len(set(names)):
        raise BuilderError("lock", f"duplicate package in {lock_path.name}")
    if names != sorted(names):
        raise BuilderError("lock", f"package set not sorted in {lock_path.name}")
    if {name: version for name, version in zip(names, (w.version for w in wheels))} != expected_versions:
        raise BuilderError("lock", f"package-set identity mismatch in {lock_path.name}")

    target = config["target"]
    torch_backend = variant_config["torch_backend"]
    return Lock(
        variant=variant,
        schema=LOCK_SCHEMA,
        target_python=target["python"],
        target_platform=target["platform"],
        wheel_platform=target["wheel_platform"],
        resolver=resolver,
        resolver_config_sha256=config_hash,
        generator_sha256=generator_hash,
        lock_filename=lock_path.name,
        lock_sha256=locklib.sha256_file_text_canonical(lock_path),
        input_hashes=dict(sorted(input_hashes.items())),
        input_identity_sha256=expected_input_identity,
        torch_backend=torch_backend,
        gui=variant.endswith("-gui"),
        wheels=tuple(wheels),
    )


def load_inputs(
    repo_root: Path = REPO_ROOT, variant: str = ""
) -> tuple[PythonAsset, PythonLicenseInventory, Lock, str]:
    """Load and re-verify every Commit-1 input for one variant.

    The returned lock identity re-validates freshness: stale resolver-config,
    generator, or direct-input hashes are rejected before any build work.
    """
    if variant and variant not in VARIANTS:
        raise BuilderError("variant", f"unknown variant: {variant!r}")
    config = locklib.load_json(repo_root / "runtime-lock.json")
    if set(config.get("variants", {})) != set(VARIANTS):
        raise BuilderError("identity", "runtime-lock.json variant set deviates from the Commit-1 contract")
    identity = load_python_identity(repo_root)
    inventory = load_license_inventory(repo_root, identity)
    if not variant:
        bootstrap = locklib.sha256_file_text_canonical(repo_root / BOOTSTRAP_RELATIVE)
        return identity, inventory, _empty_lock(config), bootstrap
    lock = load_lock(repo_root, config, variant)
    bootstrap = locklib.sha256_file_text_canonical(repo_root / BOOTSTRAP_RELATIVE)
    return identity, inventory, lock, bootstrap


