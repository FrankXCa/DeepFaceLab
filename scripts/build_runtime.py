def _add_runtime_root(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--runtime-root",
        type=Path,
        default=None,
        help="runtime tree location (default: <repo>/runtime)",
    )


def _resolve_runtime_root(args: argparse.Namespace) -> Path:
    root = args.runtime_root if args.runtime_root is not None else REPO_ROOT / "runtime"
    return root if root.is_absolute() else REPO_ROOT / root


def _default_cache_dir() -> Path:
    return REPO_ROOT / ".cache" / "portable-runtime"


def _prepare_build_context(args: argparse.Namespace, variant: str) -> BuildContext:
    runtime_root = _resolve_runtime_root(args)
    identity, inventory, lock, bootstrap = load_inputs(REPO_ROOT, variant)
    offline = getattr(args, "offline", False)
    if offline:
        offline_inputs = getattr(args, "offline_inputs", None)
        if offline_inputs is None:
            raise BuilderError("offline", "--offline requires --offline-inputs DIR")
        offline_dir = Path(offline_inputs)
        if not offline_dir.is_absolute():
            offline_dir = REPO_ROOT / offline_dir
        if not offline_dir.is_dir():
            raise BuilderError("offline", f"offline-inputs directory missing: {offline_dir.name}")
        # Strict contract BEFORE anything is staged: complete exact layout,
        # exact directory topology, license inventory equal to the Commit-1
        # authority, every lock copy byte-exact against the AUTHORITATIVE
        # repository contract bytes, no unexpected files, and (by
        # construction of OfflineFetcher) no network path that could
        # execute.
        contract_bytes = {
            name: (REPO_ROOT / name).read_bytes()
            for name in _offline_lock_filenames(variant)
        }
        verify_offline_inputs(offline_dir, variant, identity, inventory, lock, contract_bytes)
        fetcher: object = OfflineFetcher(offline_dir, variant)
    else:
        cache_dir = getattr(args, "artifact_cache", None) or _default_cache_dir()
        if not cache_dir.is_absolute():
            cache_dir = REPO_ROOT / cache_dir
        fetcher = OnlineFetcher(cache_dir, variant)
        contract_bytes = None
    return BuildContext(
        repo_root=REPO_ROOT,
        runtime_root=runtime_root,
        identity=identity,
        inventory=inventory,
        lock=lock,
        bootstrap_sha256=bootstrap,
        fetcher=fetcher,
        installer=SubprocessPipInstaller(),
        interpreter=SubprocessInterpreter(),
        activate=bool(getattr(args, "activate", False)),
        lock_timeout=float(getattr(args, "lock_timeout", 3600.0)),
        offline_contract_bytes=contract_bytes,
    )


def cmd_build(args: argparse.Namespace) -> int:
    if args.offline and getattr(args, "offline_inputs", None) is None:
        print("build: --offline requires --offline-inputs DIR", file=sys.stderr)
        return 2
    ctx = _prepare_build_context(args, args.variant)
    result = run_build(ctx)
    print(f"build: {result.state} runtime {result.runtime_id} (variant {ctx.lock.variant})")
    if result.activated:
        print(f"build: active-runtime pointer -> {result.runtime_id}")
    return 0


def _resolve_variant(args: argparse.Namespace, runtime_dir: Path, command: str) -> str | None:
    """Explicit --variant wins; otherwise the manifest's variant is authoritative."""
    if args.variant is not None:
        if args.variant not in VARIANTS:
            print(f"{command}: unknown --variant {args.variant!r}", file=sys.stderr)
            return None
        return args.variant
    manifest_path = runtime_dir / MANIFEST_NAME
    if not manifest_path.is_file():
        print(f"{command}: missing runtime-manifest.json; pass --variant", file=sys.stderr)
        return None
    variant = read_manifest(manifest_path).get("canonical", {}).get("variant", "")
    if variant not in VARIANTS:
        print(f"{command}: manifest variant {variant!r} is not a Commit-1 variant", file=sys.stderr)
        return None
    return variant


def cmd_verify_runtime(args: argparse.Namespace) -> int:
    runtime_root = _resolve_runtime_root(args)
    runtime_dir = runtime_root / VERSIONS_DIRNAME / args.runtime_id
    if not RUNTIME_ID_RE.fullmatch(args.runtime_id):
        print(f"verify-runtime: invalid runtime id grammar: {args.runtime_id!r}", file=sys.stderr)
        return 2
    if not runtime_dir.is_dir():
        print(f"verify-runtime: runtime not found: versions/{args.runtime_id}", file=sys.stderr)
        return 1
    variant = _resolve_variant(args, runtime_dir, "verify-runtime")
    if variant is None:
        return 1
    identity, inventory, lock, bootstrap = load_inputs(REPO_ROOT, variant)
    checks = verify_runtime(runtime_dir, lock, identity, inventory, bootstrap)
    failed = [c for c in checks if c.code != "PASS"]
    for check in checks:
        line = f"  {check.name}: {check.code}"
        if check.note:
            line += f" ({check.note})"
        print(line)
    if failed:
        print(f"verify-runtime: FAIL ({len(failed)} of {len(checks)} checks)")
        return 1
    print(f"verify-runtime: PASS ({len(checks)} checks)")
    return 0


def _cmd_activate_like(args: argparse.Namespace, command: str) -> int:
    runtime_root = _resolve_runtime_root(args)
    runtime_dir = runtime_root / VERSIONS_DIRNAME / args.runtime_id
    if not RUNTIME_ID_RE.fullmatch(args.runtime_id):
        print(f"{command}: invalid runtime id grammar: {args.runtime_id!r}", file=sys.stderr)
        return 2
    if not runtime_dir.is_dir():
        print(f"{command}: runtime not found: versions/{args.runtime_id}", file=sys.stderr)
        return 1
    variant = _resolve_variant(args, runtime_dir, command)
    if variant is None:
        return 1
    identity, inventory, _lock, bootstrap = load_inputs(REPO_ROOT, variant)
    setup_lock = SetupActivationLock(runtime_root, float(args.lock_timeout)).acquire()
    try:
        try:
            previous = perform_activation(
                runtime_root,
                args.runtime_id,
                identity,
                inventory,
                bootstrap,
                _variant_lock_loader(REPO_ROOT),
                setup_lock,
                command,
            )
        except BuilderError as exc:
            print(f"{command}: {exc.message}", file=sys.stderr)
            return 1
        print(f"{command}: active-runtime pointer -> {args.runtime_id}")
        if previous:
            print(f"{command}: previous {previous} retained under versions/")
        return 0
    finally:
        setup_lock.release()


def cmd_activate(args: argparse.Namespace) -> int:
    return _cmd_activate_like(args, "activate")


def cmd_rollback(args: argparse.Namespace) -> int:
    return _cmd_activate_like(args, "rollback")


def cmd_fetch_offline_inputs(args: argparse.Namespace) -> int:
    cache_dir = args.artifact_cache or _default_cache_dir()
    if not cache_dir.is_absolute():
        cache_dir = REPO_ROOT / cache_dir
    output = args.output
    if output is None:
        # Default into the ignored offline-inputs/ directory so the generated
        # layout (offline-inputs/<variant>/...) is covered by .gitignore.
        output = REPO_ROOT / "offline-inputs" / args.variant
    elif not output.is_absolute():
        output = REPO_ROOT / output
    fetch_offline_inputs(REPO_ROOT, args.variant, Path(output), cache_dir)
    return 0


def main(argv: list[str] | None = None) -> int:
    if sys.version_info < MIN_HOST_PYTHON:
        print(
            "build-runtime: host Python >= 3.11 is required to run the builder "
            f"(running {sys.version.split()[0]})",
            file=sys.stderr,
        )
        return 2
    parser = argparse.ArgumentParser(
        prog="build_runtime.py",
        description=__doc__.splitlines()[0],
        epilog=_SUBCOMMAND_HELP,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p_build = sub.add_parser("build", help="assemble, verify, and promote a portable runtime")
    p_build.add_argument("--variant", required=True, help="cuda-gui|cuda-nogui|cpu-gui|cpu-nogui")
    _add_runtime_root(p_build)
    p_build.add_argument("--offline", action="store_true", help="offline build: no network access")
    p_build.add_argument("--offline-inputs", type=Path, default=None, help="explicit offline-inputs directory")
    p_build.add_argument("--artifact-cache", type=Path, default=None, help="developer artifact cache directory")
    p_build.add_argument("--activate", action="store_true", help="activate the built runtime afterwards")
    p_build.add_argument("--lock-timeout", type=float, default=3600.0, help="seconds to wait for the setup/activation lock")
    p_build.set_defaults(func=cmd_build)

    p_verify = sub.add_parser("verify-runtime", help="verify an existing runtime against its manifest")
    p_verify.add_argument("--runtime-id", required=True, help="64-hex runtime id under runtime/versions/")
    p_verify.add_argument("--variant", default=None, help="override the manifest variant (Commit-1 variant names only)")
    _add_runtime_root(p_verify)
    p_verify.set_defaults(func=cmd_verify_runtime)

    for name, func, help_text in (
        ("activate", cmd_activate, "atomically activate a verified runtime"),
        ("rollback", cmd_rollback, "activate a retained previously-active runtime"),
    ):
        p = sub.add_parser(name, help=help_text)
        p.add_argument("--runtime-id", required=True, help="64-hex runtime id under runtime/versions/")
        p.add_argument("--variant", default=None, help="override the manifest variant")
        _add_runtime_root(p)
        p.add_argument("--lock-timeout", type=float, default=3600.0)
        p.set_defaults(func=func)

    p_fetch = sub.add_parser("fetch-offline-inputs", help="prepare an offline-inputs directory")
    p_fetch.add_argument("--variant", required=True)
    p_fetch.add_argument(
        "--output",
        type=Path,
        default=None,
        help="offline-inputs directory (default: <repo>/offline-inputs/<variant>, which .gitignore ignores)",
    )
    p_fetch.add_argument("--artifact-cache", type=Path, default=None)
    p_fetch.set_defaults(func=cmd_fetch_offline_inputs)

    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except BuilderError as exc:
        print(f"build-runtime: {exc.code}: {exc.message}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("build-runtime: interrupted", file=sys.stderr)
        return 130


if __name__ == "__main__":
    raise SystemExit(main())
