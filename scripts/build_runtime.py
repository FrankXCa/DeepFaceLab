#!/usr/bin/env python3
"""Assemble and verify Phase-13 DeepFaceLab portable Windows runtimes.

Commit-2 scope: portable runtime ASSEMBLY and the MANIFEST workflow. This tool
consumes the immutable Commit-1 input contract

    runtime-python.json               pinned standalone Python 3.12.11 asset
    runtime-python-licenses.json      recursive Python license inventory
    runtime-lock.json                 variant/resolver/target configuration
    requirements-lock-<variant>.txt   exact per-variant artifact locks

and constructs versioned, immutable portable runtimes:

    runtime/
      versions/<runtime-id>/          immutable verified runtime
        python.exe, Lib/...           stripped standalone Python tree
        runtime-manifest.json         privacy-safe deterministic manifest
      .staging/<runtime-id>-<nonce>/  build candidate (never exposed as verified)
      active-runtime.txt              selector pointer (explicit activation only)
      activation.lock                 setup/activation serialization lock

Subcommands:

    build                 assemble, verify, and promote a variant (optionally
                          activating the newly built runtime afterwards)
    verify-runtime        verify an existing runtime directory against its
                          manifest and the Commit-1 contract (static checks)
    activate              atomically point active-runtime.txt at a verified
                          runtime (low-level primitive; launcher UX is later)
    rollback              activate a retained (previously active) verified
                          runtime using the same atomic pointer swap
    fetch-offline-inputs  prepare an offline-inputs directory from the exact
                          online sources for later offline assembly

Build semantics (all enforced by the builder):

  * The exact pinned standalone Python archive is verified by SHA-256 BEFORE
    extraction; no "latest" release, no redirected substitute identity, no
    different flavor or target is accepted.
  * Archive extraction is member-validated into a freshly owned EMPTY
    destination: path traversal, absolute member paths, Windows drive-
    qualified names, ADS/colon names, Windows reserved device names
    (NUL/CON/COM1-9/LPT1-9), entries escaping the staging root, duplicate
    members, case-insensitive name collisions, symlink/hardlink members,
    reparse-point (junction) targets, and existing write targets are all
    rejected. Nothing is extracted outside the staging root and nothing is
    ever overwritten.
  * The recursive Python license inventory from Commit 1 is re-verified on
    the extracted tree (expected paths exist, SHA-256 matches, source
    identity matches the pinned archive).
  * Wheel installation is a no-resolution install into the staged runtime's
    own Python:
        <staged-python> -I -B -m pip install
            --no-index --no-deps --require-hashes --only-binary=:all:
    with a requirements file containing only the exact locked local wheel
    files plus their locked SHA-256 hashes. No PyPI resolution, no sdist,
    no build-from-source, no substitution.
  * Every artifact (Python archive and each wheel) is SHA-256 verified before
    use. Corrupt cached artifacts are rejected (online: re-fetched once;
    offline: hard failure, no network fallback).
  * Offline mode performs no network access at all: before staging it
    validates the COMPLETE offline-inputs layout — a valid
    artifact-manifest.json naming the variant and matching the pinned Python
    asset and the exact locked wheel set, every locked wheel present with its
    locked hash, the Commit-1 Python license inventory reproduced under
    licenses/, every Commit-1 contract file under locks/ with an
    exact-hash-matched selected lock copy, and NO file outside that exact
    structure. Any incomplete, mismatched, or extraneous layout is rejected;
    no network path can execute.
  * After installation the builder verifies the installed package set against
    the selected lock (interpreter-bundled baseline distributions plus the
    locked set, exact name+version), the variant contract (PyQt5 family for
    GUI variants only; torch local version tag for CUDA/CPU), runs basic
    imports using the ASSEMBLED portable Python, runs the runtime_entry.py
    isolated-bootstrap self-test, scrubs generated bytecode, recognizes ONLY
    the exact reviewed SciPy 1.18.1 self-copy artifact (retained, recorded in
    the operational manifest; any other archive file fails closed), removes
    direct_url.json provenance pointers together with their RECORD lines,
    drops the RECORD entries of the scrubbed generated bytecode (so the
    on-disk RECORD is self-consistent and every remaining entry is
    byte-verified), scans for prohibited cache classes, and writes a scoped
    installed-tree inventory.
  * verify_runtime anchors the runtime to the CURRENT Commit-1 repository
    inputs (runtime-lock.json, runtime-python.json,
    runtime-python-licenses.json, the selected requirements lock, the current
    scripts/runtime_entry.py bootstrap hash, this builder's contract): the
    EXPECTED runtime ID is computed from those current inputs plus the
    installed-tree integrity digest recomputed from the ACTUAL tree, and the
    directory name, the manifest's runtime ID, and the manifest's identity
    blocks (Python asset, license inventory, lock, artifacts) must all agree
    with the current authority. The runtime manifest is evidence/metadata,
    never the authority that defines which files or packages are verified:
    installed distributions are re-enumerated from the filesystem
    (duplicates rejected, exact normalized key set required), and payload
    integrity is anchored to the runtime ID (see below), so no mutable
    manifest field can remove or redirect verification coverage.
  * The runtime ID is the SHA-256 of a canonical document built from: the
    builder contract/version, scripts/runtime_entry.py bootstrap SHA-256,
    the pinned Python asset identity, the Python license inventory SHA-256,
    the variant, the artifact lock identity (lock file SHA-256, resolver
    SHA-256, direct input SHA-256 set, input-identity SHA-256), and the
    CANONICAL INSTALLED-TREE INTEGRITY DIGEST (the SHA-256 of the sorted
    {relative-path: SHA-256} map over the actual bytes of every file in the
    normalized build output). The tree digest is build output (Commit 2)
    that is itself deterministic for identical inputs, so including it keeps
    equivalent builds canonically reproducible while cryptographically
    binding the runtime ID to the exact frozen tree: any post-build
    modification of payload, RECORD, manifest, or tree structure changes
    the recomputed digest, changes the expected ID, and fails verification
    against the (immutable) directory name. No wall clock, no randomness,
    no host path, username, hostname, or IP takes part.
  * Console-script launcher contract: pip-generated Scripts/*.exe binaries
    embed build-machine paths and are not byte-reproducible, so the builder
    removes them after installation, drops their RECORD lines, and records
    the deterministic console-script entry points in the manifest instead.
    Entry points are invoked via the runtime's own interpreter
    (python -I -B -m <module> / scripts/runtime_entry.py). Any file present
    under Scripts/ in a promoted runtime is an integrity violation.
  * Baseline authority capture and narrowly-exceptioned RECORD
    reconciliation (documented upstream defect): immediately after the
    pinned archive is verified, extracted and license-checked - and
    BEFORE wheel installation or any other mutation - the builder
    captures the authoritative pre-install RECORD state of every
    bundled (interpreter-baseline) distribution: the EXACT normalized
    set of RECORD entry paths plus a digest inventory (SHA-256, size)
    for every referenced file. That captured state IS the verified
    archive's; the post-install staging tree is never used as
    authority. Reconciliation enforces, in order: (A) EXACT path
    membership - the post-install RECORD path set must equal the
    captured set minus the explicitly approved droppable paths (the
    three reviewed normalizations: direct_url pointers, scrubbed
    bytecode entries, removed launcher entries; no other class may
    disappear) - a deleted non-droppable path (whether or not its file
    was touched), an added path, a duplicate path, or a path
    case/alias collision fails the build; (B) file authority - every
    referenced file must be byte-identical to the captured archive
    bytes (size included); (C) only the reviewed exception set
    (the pinned archive's bundled pip distlib executables
    t32/t64/t64-arm/w32/w64/w64-arm.exe, whose wheel-era RECORD
    hash/size entries are stale while the files are exactly the
    archive's bytes) may have its hash/size FIELDS rewritten, and only
    to the CAPTURED values, only when the file's bytes are exactly the
    captured bytes - the path is never altered and no line is dropped;
    (D) every other stale hash/size entry fails the build closed
    before promotion. Non-baseline distributions are never touched by
    this step (their bytes are pinned by the locked wheel's SHA-256
    and must match their RECORD exactly). Any rewrite is recorded as a
    normalization entry in the operational manifest. The captured
    state is build-time-only validation state: it contains no
    absolute paths or host data and does not change the runtime ID
    inputs (the installed-tree digest already covers every tree byte).
  * The build assembles into runtime/.staging/candidate-<nonce>/ (the final
    runtime ID is only known after the tree exists, because it binds the
    installed-tree integrity digest) and only after full verification is the
    candidate atomically promoted to runtime/versions/<runtime-id>/
    (same-filesystem rename). After promotion, the FULL corrected
    verify_runtime runs against the PROMOTED path with the current Commit-1
    inputs; a fresh candidate that fails there is never reported BUILT,
    never activated, and is left in place (verified runtimes are never
    deleted). A partially built runtime is never exposed as verified.
    Existing verified runtimes are never overwritten, mutated, or deleted:
    an existing identical runtime ID is re-verified and reused; a
    mismatched existing runtime ID fails the build.
  * The setup/activation lock (runtime/activation.lock, process-held
    exclusive lock) serializes competing build/activate/rollback operations.
  * The manifest has a canonical namespace (deterministic; privacy-scanned)
    and an operational namespace (UTC timestamp, duration, informational
    notes, recorded normalizations) that never participates in identity.
    Canonical fields describe deterministic package/build identity only:
    torch CUDA hardware state (PASS / ENVIRONMENTALLY_LIMITED, device
    observations) lives exclusively in operational, so the same canonical
    inputs on a CUDA-capable host and a non-CUDA-capable host produce the
    same runtime ID and the same canonical manifest.
  * activate / rollback swap the active-runtime.txt pointer only after the
    TARGET runtime passes the full verify_runtime with the current
    Commit-1 inputs for its variant AND the RETAINED (previously active)
    runtime passes the same full verification with its OWN variant's
    current Commit-1 lock (the retained runtime may be a different
    variant, so its own variant's lock is loaded and used - manifest
    self-consistency alone is never accepted). Verified runtimes are never
    deleted by any of build/activate/rollback.

Manifest trust boundary (classified):
  * Class A - authoritative ONLY when independently recomputed from the
    current Commit-1 inputs: runtime_id (recomputed from current lock /
    python / license-inventory / bootstrap / builder identity plus the
    installed-tree digest recomputed from the actual tree), variant, python
    asset identity, license-inventory identity, lock identity (filename /
    SHA-256 / resolver / input hashes), artifact entries (name / version /
    filename / URL / source / SHA-256), console_scripts (recomputed from
    the installed entry_points.txt metadata during verification; exact
    equality with the manifest field is required).
  * Class B - consistency-only records: installed_tree (per-distribution
    METADATA / normalized-RECORD digests and root-file hashes; the
    authoritative binding is the runtime-ID tree digest), interpreter_
    baseline (re-verified against the tree), recorded normalizations.
  * Class C - operational / non-canonical: timestamps, durations, notes,
    torch hardware observations.
  A or B fields are NEVER used to define which files, distributions, or
  RECORD entries get verified: verification scope is derived from the
  current lock and the actual filesystem, and payload integrity is
  anchored to the runtime ID (tree digest over actual file bytes).

Host/runtime distinction: construction may use a developer host Python
>= 3.11 (stdlib only). The assembled runtime contains its own standalone
CPython 3.12.11 and does not depend on any host Python at run time.
"""

