def distributions_from_probe(raw: dict[str, list[str]]) -> tuple[dict[str, set[str]], dict[str, str]]:
    """Split probe output into normalized {name: versions} and {name: dist_info}."""
    versions: dict[str, set[str]] = {}
    dist_info: dict[str, str] = {}
    for name, values in raw.items():
        normalized = locklib.normalized_name(name)
        for value in values:
            if value.startswith("@@DISTINFO@@"):
                if value[len("@@DISTINFO@@") :]:
                    dist_info.setdefault(normalized, value[len("@@DISTINFO@@") :])
                continue
            versions.setdefault(normalized, set()).add(value)
    return versions, dist_info


def _isolated_env() -> dict[str, str]:
    """Host environment with every Python/pip-influencing variable removed."""
    env = {
        key: value
        for key, value in os.environ.items()
        if not (key.startswith("PYTHON") or key.startswith("PIP"))
    }
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["PYTHONNOUSERSITE"] = "1"
    return env


class SubprocessInterpreter:
    """Runs probe commands with the assembled portable Python, isolated."""

    def __init__(self, timeout: float = 900.0) -> None:
        self.timeout = timeout

    def run(
        self,
        python_exe: Path,
        *args: str,
        cwd: Path | None = None,
        timeout: float | None = None,
    ) -> subprocess.CompletedProcess[str]:
        env = _isolated_env()
        command = [str(python_exe), "-I", "-B", *[str(a) for a in args]]
        return subprocess.run(
            command,
            env=env,
            cwd=str(cwd) if cwd is not None else None,
            capture_output=True,
            text=True,
            timeout=timeout if timeout is not None else self.timeout,
        )


class SubprocessPipInstaller:
    """No-resolution wheel install into the staged runtime's own Python."""

    PIP_FLAGS = (
        "--no-index",
        "--no-deps",
        "--require-hashes",
        "--only-binary=:all:",
        "--disable-pip-version-check",
        "--no-input",
    )

    def __init__(self, timeout: float = 3600.0) -> None:
        self.timeout = timeout

    def install(self, python_exe: Path, requirements_file: Path, cwd: Path, cache_dir: Path) -> None:
        env = _isolated_env()
        cache_dir.mkdir(parents=True, exist_ok=True)
        command = [
            str(python_exe), "-I", "-B", "-m", "pip", "install",
            *self.PIP_FLAGS,
            "--cache-dir", str(cache_dir),
            "-r", str(requirements_file),
        ]
        try:
            proc = subprocess.run(
                command,
                env=env,
                cwd=str(cwd),
                capture_output=True,
                text=True,
                timeout=self.timeout,
            )
        except subprocess.TimeoutExpired as exc:
            raise BuilderError("install", f"pip install timed out after {self.timeout:.0f}s") from exc
        if proc.returncode != 0:
            tail = (proc.stderr or proc.stdout or "").strip().splitlines()[-12:]
            raise BuilderError("install", "pip install failed: " + " | ".join(tail))


