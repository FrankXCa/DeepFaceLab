def _is_reparse_point(path: Path) -> bool:
    """True if `path` is a Windows junction/reparse point; False elsewhere."""
    if os.name != "nt":
        return False
    try:
        attrs = os.stat(path, follow_symlinks=False).st_file_attributes
    except OSError:
        return False
    return bool(attrs & 0x400)  # FILE_ATTRIBUTE_REPARSE_POINT


def _assert_reparse_chain_ok(path: Path, root: Path) -> None:
    """Fail if `path` or any ancestor component down to `root` (inclusive)
    is a Windows reparse point (junction/mount point). Used to ensure a
    write target and every path component below the freshly owned staging
    root are genuine directories/files at the moment of writing."""
    current = path
    while True:
        if _is_reparse_point(current):
            raise BuilderError(
                "archive-unsafe", f"path component is a reparse point: {current}"
            )
        if current == root:
            return
        current = current.parent


def extract_python_archive(archive: Path, destination: Path) -> None:
    """Extract the standalone Python archive into `destination`.

    The archive root is `python/`; that component is stripped so the runtime
    root directly contains python.exe and the rest of the distribution.

    The destination must be a freshly owned, existing, EMPTY directory (the
    builder creates the staging candidate immediately before extraction).
    Every member is validated BEFORE anything is written:

      * no backslashes, no absolute paths, no `..` traversal
      * no Windows drive-qualified names (drive-absolute or drive-relative)
      * no colon / alternate-data-stream-style names
      * no Windows reserved device names (NUL, CON, COM1-9, LPT1-9, ...) in
        ANY path component, not just the leaf
      * no members outside the `python/` archive root
      * no symlink or hardlink members, no unsupported member types
      * no duplicate members and no case-insensitive name collisions,
        INCLUDING the archive root itself (a second `python` member - file
        or directory - is rejected)
      * final containment guard on every write target

    and the write phase never overwrites: existing files or directories at a
    target location abort the extraction, created directories are re-checked
    for reparse-point (junction) state, and before every write the ENTIRE
    path chain from the staging root down to the target is re-validated to
    be free of reparse points.

    RESIDUAL LIMITATION (documented, not overclaimed): the Python stdlib
    cannot open or replace a path without following reparse points (there is
    no no-follow CreateFile binding), so a local attacker with write access
    to the freshly owned staging root has a TOCTOU window between the
    reparse validation and the actual write. This is mitigated - not
    eliminated - by: the builder-owned empty staging directory created
    milliseconds before extraction, chain re-validation immediately before
    each write, containment guards preventing escape from the staging root,
    and the post-build full verification (installed-tree digest anchored in
    the runtime ID) which detects any file the attacker managed to plant or
    replace, because the promoted runtime is re-verified against the
    current Commit-1 inputs before it can ever be reported BUILT or
    activated.
    """
    if not destination.is_absolute():
        raise BuilderError("archive-unsafe", "extraction destination must be absolute")
    if not destination.is_dir():
        raise BuilderError("archive-unsafe", "extraction destination must be an existing directory")
    if any(destination.iterdir()):
        raise BuilderError(
            "archive-unsafe", "extraction destination must be a freshly owned empty directory"
        )
    if _is_reparse_point(destination):
        raise BuilderError("archive-unsafe", "extraction destination is a reparse point")
    destination_resolved = destination.resolve()
    with tarfile.open(archive, mode="r:gz") as package:
        planned: list[tuple[tarfile.TarInfo, str]] = []
        seen_exact: dict[str, str] = {}
        seen_casefolded: dict[str, str] = {}
        for member in package.getmembers():
            name = member.name
            if "\\" in name:
                raise BuilderError("archive-unsafe", f"backslash in archive member name: {name}")
            if name.startswith("/"):
                raise BuilderError("archive-unsafe", f"absolute archive member: {name}")
            if re.match(r"^[A-Za-z]:", name):
                raise BuilderError("archive-unsafe", f"windows drive-qualified archive member: {name}")
            if ":" in name:
                raise BuilderError("archive-unsafe", f"ADS-style colon in archive member name: {name}")
            posix = PurePosixPath(name)
            if ".." in posix.parts:
                raise BuilderError("archive-unsafe", f"path-traversal archive member: {name}")
            if name != PYTHON_ARCHIVE_ROOT and not name.startswith(PYTHON_ARCHIVE_ROOT + "/"):
                raise BuilderError(
                    "archive-unsafe", f"archive member outside {PYTHON_ARCHIVE_ROOT}/ root: {name}"
                )
            if member.issym() or member.islnk():
                raise BuilderError(
                    "archive-unsafe",
                    f"link members are not permitted in the Python archive: {name}",
                )
            if not (member.isdir() or member.isfile()):
                raise BuilderError("archive-unsafe", f"unsupported archive member type: {name}")
            # Reserved device-name check on EVERY path component (a member
            # such as python/NUL/x or python/COM1/data is a hazard even when
            # the leaf is harmless).
            for component in posix.parts:
                if component.split(".", 1)[0].upper() in WINDOWS_RESERVED_DEVICE_NAMES:
                    raise BuilderError(
                        "archive-unsafe",
                        f"windows device-name hazard in archive member: {name}",
                    )
            # Duplicate / case-collision detection on the RAW name, which
            # also covers the stripped archive root (`python`): a second
            # root member (file or directory) is rejected instead of being
            # silently skipped.
            if name in seen_exact:
                raise BuilderError(
                    "archive-unsafe",
                    f"duplicate archive member: {name} (already {seen_exact[name]})",
                )
            if name.casefold() in seen_casefolded:
                raise BuilderError(
                    "archive-unsafe",
                    f"case-insensitive archive member collision: {name} collides with "
                    f"{seen_casefolded[name.casefold()]}",
                )
            seen_exact[name] = name
            seen_casefolded[name.casefold()] = name
            relative = "" if name == PYTHON_ARCHIVE_ROOT else name[len(PYTHON_ARCHIVE_ROOT) + 1 :]
            planned.append((member, relative))
        for member, relative in planned:
            target = destination_resolved if relative == "" else destination_resolved / relative
            if not (target == destination_resolved or destination_resolved in target.parents):
                raise BuilderError("archive-unsafe", f"archive entry escapes staging root: {member.name}")
            if member.isdir():
                if target.exists() and not target.is_dir():
                    raise BuilderError(
                        "archive-unsafe", f"existing extraction target is not a directory: {member.name}"
                    )
                target.mkdir(parents=True, exist_ok=True)
                # Re-validate the created directory AND its whole chain below
                # the staging root (TOCTOU mitigation).
                _assert_reparse_chain_ok(target, destination_resolved)
                continue
            if target.exists():
                raise BuilderError(
                    "archive-unsafe", f"refusing to overwrite existing extraction target: {member.name}"
                )
            # Re-validate the whole chain from the staging root down to the
            # parent (TOCTOU mitigation) immediately before writing.
            _assert_reparse_chain_ok(target.parent, destination_resolved)
            target.parent.mkdir(parents=True, exist_ok=True)
            _assert_reparse_chain_ok(target.parent, destination_resolved)
            stream = package.extractfile(member)
            if stream is None:
                raise BuilderError("archive-unsafe", f"could not read archive member: {member.name}")
            with stream:
                data = stream.read()
            target.write_bytes(data)
            os.utime(target, (member.mtime, member.mtime))


def discover_installed_licenses(runtime_dir: Path) -> dict[str, tuple[str, str]]:
    """Casefolded installed-relative path -> (path, sha256) for license files."""
    discovered: dict[str, tuple[str, str]] = {}
    for path in sorted(runtime_dir.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(runtime_dir).as_posix()
        if not locklib.license_path_matches(PurePosixPath(relative)):
            continue
        discovered[relative.casefold()] = (relative, locklib.sha256_file_raw(path))
    return discovered


def _under_site_packages_directory(key: str) -> bool:
    """True for a casefolded POSIX-relative path that sits under a
    subdirectory of ``Lib/site-packages/`` (e.g. ``cv2/license-3rd-party.txt``).

    Such files belong to a distribution installed into the runtime (or to the
    interpreter's own pip, whose LICENSE.txt is an inventory entry), not to
    the standalone Python asset; the Python license inventory verifies the
    asset, so these cannot be "extra" entries. License files at the
    site-packages ROOT (one level only) remain subject to EXTRA detection."""
    parts = key.split("/")
    return len(parts) >= 4 and parts[0] == "lib" and parts[1] == "site-packages"


def check_python_license_tree(
    runtime_dir: Path,
    inventory: PythonLicenseInventory,
    identity: PythonAsset,
) -> list[Check]:
    """Verify the pinned Python license inventory against the tree.

    All inventory entries must exist with the pinned SHA-256; any license
    file outside the inventory (outside installed package directories) is an
    unexpected EXTRA_ENTRY. This is safe both pre-install (fresh extraction,
    where the whole tree is the Python asset) and post-install / on promoted
    runtimes, where installed packages contribute their own license files
    inside ``Lib/site-packages/<package>/...``."""
    discovered = discover_installed_licenses(runtime_dir)
    for entry in inventory.entries:
        if entry.source_archive_filename != identity.filename:
            return [Check("python_license_inventory", "SOURCE_MISMATCH", entry.archive_path)]
        if entry.source_archive_sha256 != identity.sha256:
            return [Check("python_license_inventory", "SOURCE_MISMATCH", entry.archive_path)]
    for entry in inventory.entries:
        found = discovered.get(entry.installed_path.casefold())
        if found is None:
            return [Check("python_license_inventory", "MISSING_ENTRY", entry.installed_path)]
        if found[1] != entry.sha256:
            return [Check("python_license_inventory", "HASH_MISMATCH", entry.installed_path)]
    expected_keys = {entry.installed_path.casefold() for entry in inventory.entries}
    extras = sorted(
        key for key in (set(discovered) - expected_keys)
        if not _under_site_packages_directory(key)
    )
    if extras:
        return [Check("python_license_inventory", "EXTRA_ENTRY", extras[0])]
    return [Check("python_license_inventory", "PASS", f"{len(inventory.entries)} license entries verified")]


