@dataclass(frozen=True)
class ArtifactSpec:
    kind: str  # "python" | "wheel"
    filename: str
    url: str
    sha256: str


def python_spec(identity: PythonAsset) -> ArtifactSpec:
    return ArtifactSpec("python", identity.filename, identity.source_url, identity.sha256)


def wheel_specs(lock: Lock) -> list[ArtifactSpec]:
    return [
        ArtifactSpec("wheel", wheel.filename, wheel.url, wheel.sha256)
        for wheel in lock.wheels
    ]


def _default_opener(url: str):
    request = urllib.request.Request(url, headers={"User-Agent": "DeepFaceLab-runtime-builder/1"})
    return urllib.request.urlopen(request, timeout=300)


class OnlineFetcher:
    """Hash-verified artifact cache with online re-fetch on miss/corruption."""

    network_enabled = True

    def __init__(self, cache_dir: Path, variant: str, opener=_default_opener) -> None:
        self.cache_dir = Path(cache_dir)
        self.variant = variant
        self.opener = opener

    def cache_path(self, spec: ArtifactSpec) -> Path:
        base = "python" if spec.kind == "python" else Path("wheels") / self.variant
        return self.cache_dir / base / spec.filename

    def fetch(self, spec: ArtifactSpec) -> Path:
        target = self.cache_path(spec)
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            if locklib.sha256_file_raw(target) == spec.sha256:
                return target
            target.unlink()  # corrupt cache entry: never trusted, re-fetched
        part = target.with_name(target.name + ".part")
        try:
            stream = self.opener(spec.url)
        except Exception as exc:  # noqa: BLE001 - network failure boundary
            part.unlink(missing_ok=True)
            raise BuilderError(
                "artifact-fetch", f"could not fetch {spec.filename}: {type(exc).__name__}"
            ) from exc
        with stream, part.open("wb") as out:
            shutil.copyfileobj(stream, out, 1024 * 1024)
        if locklib.sha256_file_raw(part) != spec.sha256:
            part.unlink(missing_ok=True)
            raise BuilderError(
                "artifact-hash",
                f"downloaded artifact failed SHA-256 verification: {spec.filename}",
            )
        os.replace(part, target)
        return target


class OfflineFetcher:
    """Artifact source restricted to one explicit offline-inputs directory."""

    network_enabled = False

    def __init__(self, offline_dir: Path, variant: str) -> None:
        self.offline_dir = Path(offline_dir)
        self.variant = variant

    def cache_path(self, spec: ArtifactSpec) -> Path:
        base = "python" if spec.kind == "python" else Path("wheels") / self.variant
        return self.offline_dir / base / spec.filename

    def fetch(self, spec: ArtifactSpec) -> Path:
        target = self.cache_path(spec)
        if not target.is_file():
            raise BuilderError(
                "artifact-missing",
                f"offline artifact missing: {spec.filename} "
                f"(expected under offline-inputs/{target.relative_to(self.offline_dir).as_posix()})",
            )
        if locklib.sha256_file_raw(target) != spec.sha256:
            raise BuilderError(
                "artifact-hash",
                f"offline artifact failed SHA-256 verification: {spec.filename}",
            )
        return target


