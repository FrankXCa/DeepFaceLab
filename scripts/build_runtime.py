def compute_runtime_id(
    bootstrap_sha256: str,
    identity: PythonAsset,
    inventory: PythonLicenseInventory,
    lock: Lock,
    tree_sha256: str,
) -> str:
    """Deterministic runtime ID over the canonical Commit-2 identity.

    Participating inputs (documented):
      * builder contract + builder version (this tool's schema)
      * scripts/runtime_entry.py bootstrap SHA-256 (isolation/bootstrap identity)
      * pinned Python asset identity (project, implementation, version, release,
        target triple, CPU baseline, flavor, filename, source URL, SHA-256)
      * Python license inventory SHA-256 (Commit-1 contract over the archive)
      * variant
      * artifact lock identity (lock file SHA-256, resolver identity,
        direct input SHA-256 set, input-identity SHA-256)
      * installed-tree integrity digest (`tree_sha256`): the canonical
        SHA-256 over the ACTUAL bytes of every file in the normalized build
        output. It is build output (Commit 2), but deterministic for
        identical inputs, so identical builds remain canonically
        reproducible while the runtime ID cryptographically binds the exact
        frozen tree: post-build modification of any file (payload, RECORD,
        METADATA, tree structure) changes the recomputed digest and the
        expected ID, and verification against the immutable directory name
        fails.
    """
    payload = {
        "builder": {"contract": BUILDER_CONTRACT, "version": BUILDER_VERSION},
        "bootstrap": {"path": BOOTSTRAP_RELATIVE, "sha256": bootstrap_sha256},
        "python": identity.canonical(),
        "python_license_inventory_sha256": inventory.inventory_sha256,
        "variant": lock.variant,
        "lock": {
            "filename": lock.lock_filename,
            "sha256": lock.lock_sha256,
            "resolver": lock.resolver,
            "resolver_config_sha256": lock.resolver_config_sha256,
            "input_hashes": dict(sorted(lock.input_hashes.items())),
            "input_identity_sha256": lock.input_identity_sha256,
        },
        "installed_tree_inventory_sha256": tree_sha256,
    }
    return locklib.sha256_bytes(locklib.canonical_json(payload).encode("ascii"))


