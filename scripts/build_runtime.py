class SetupActivationLock:
    """Process-held exclusive lock serializing build/activate/rollback.

    The lock lives on the runtime tree (runtime/activation.lock). It is held
    for the full competing operation and is released by process exit, so no
    stale-file recovery is required.
    """

    def __init__(self, runtime_root: Path, timeout_seconds: float = 3600.0) -> None:
        self.runtime_root = Path(runtime_root)
        self.timeout_seconds = timeout_seconds
        self.path = self.runtime_root / ACTIVATION_LOCK_NAME
        self._handle = None

    def acquire(self) -> "SetupActivationLock":
        self.runtime_root.mkdir(parents=True, exist_ok=True)
        self._handle = os.open(self.path, os.O_RDWR | os.O_CREAT, 0o666)
        deadline = time.monotonic() + self.timeout_seconds
        while True:
            try:
                self._lock_exclusive(self._handle)
                return self
            except (BlockingIOError, PermissionError, InterruptedError):
                if time.monotonic() >= deadline:
                    self._close()
                    raise BuilderError(
                        "lock-busy",
                        "setup/activation lock is held by another builder or setup process; "
                        "retry later or extend --lock-timeout",
                    )
                time.sleep(0.25)

    def release(self) -> None:
        if self._handle is None:
            return
        try:
            if os.name == "nt":
                msvcrt.locking(self._handle, msvcrt.LK_UNLCK, 1)
            else:  # pragma: no cover
                fcntl.flock(self._handle, fcntl.LOCK_UN)
        finally:
            self._close()

    def _close(self) -> None:
        if self._handle is not None:
            os.close(self._handle)
            self._handle = None

    def _lock_exclusive(self, handle: int) -> None:
        if os.name == "nt":
            msvcrt.locking(handle, msvcrt.LK_NBLCK, 1)
        else:  # pragma: no cover
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)

    def __enter__(self) -> "SetupActivationLock":
        return self.acquire()

    def __exit__(self, *exc_info) -> None:
        self.release()


def set_active_pointer(runtime_root: Path, runtime_id: str) -> str | None:
    """Atomically swap active-runtime.txt; returns the previous selector value."""
    if not RUNTIME_ID_RE.fullmatch(runtime_id):
        raise BuilderError("state", f"invalid runtime id grammar: {runtime_id!r}")
    runtime_root = Path(runtime_root)
    pointer = runtime_root / ACTIVE_POINTER_NAME
    previous = pointer.read_text(encoding="utf-8").strip() if pointer.is_file() else None
    tmp = pointer.with_name(ACTIVE_POINTER_NAME + ".tmp")
    tmp.write_bytes((runtime_id + "\n").encode("ascii"))
    with tmp.open("r+b") as stream:
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(tmp, pointer)
    return previous


def _manifest_variant(runtime_dir: Path) -> str:
    """Read a runtime's recorded variant from its manifest (fail closed).

    Used by activation/rollback to select the CURRENT Commit-1 lock of the
    retained runtime's own variant: the retained runtime may be a different
    variant than the target, and it must be verified with its own variant's
    current lock inputs - never with manifest self-consistency alone."""
    manifest_path = runtime_dir / MANIFEST_NAME
    if not manifest_path.is_file():
        raise BuilderError(
            "state",
            f"runtime {runtime_dir.name}: manifest missing; its variant cannot be determined",
        )
    manifest = read_manifest(manifest_path)
    canonical = manifest.get("canonical", {})
    if manifest.get("schema") != MANIFEST_SCHEMA or canonical.get("schema") != MANIFEST_SCHEMA:
        raise BuilderError(
            "state",
            f"runtime {runtime_dir.name}: manifest schema mismatch; its variant cannot be determined",
        )
    variant = canonical.get("variant", "")
    if variant not in VARIANTS:
        raise BuilderError(
            "state",
            f"runtime {runtime_dir.name}: manifest variant {variant!r} is not a known variant",
        )
    return variant


def perform_activation(
    runtime_root: Path,
    target_id: str,
    identity: PythonAsset,
    inventory: PythonLicenseInventory,
    bootstrap_sha256: str,
    lock_for_variant,
    setup_lock: SetupActivationLock,
    command: str,
) -> str | None:
    """Atomically point the active-runtime selector at `target_id`.

    The caller MUST already hold the setup/activation lock (the lock object
    is accepted so the same code path serves ``build --activate``, the
    standalone ``activate`` command and ``rollback``).

    `lock_for_variant` must return the CURRENT Commit-1 artifact lock for a
    variant (e.g. the loader built by ``_variant_lock_loader``); it is used
    to fully verify BOTH runtimes below with the current authoritative
    inputs of each of their own variants.

    Sequence:

      1. target runtime id grammar is validated (64 hex chars);
      2. the CURRENT selector's syntax/grammar is validated: a malformed
         active-runtime.txt blocks the swap (fail closed);
      3. the target runtime exists and passes the FULL corrected
         ``verify_runtime`` (current-input authority: builder/bootstrap /
         python / license-inventory / lock identity recomputed from the
         CURRENT Commit-1 inputs of the target's own variant, installed
         distributions re-enumerated from the tree with duplicate
         rejection, installed-tree integrity anchored to the runtime ID via
         the digest recomputed from the actual bytes, byte-level RECORD
         integrity) - activation is impossible for an unverified or
         tampered runtime;
      4. the RETAINED runtime (previous selector, when different) is fully
         verified with its OWN variant's current Commit-1 lock before the
         selector is replaced: it must exist, carry a parseable manifest
         variant, and pass the same full ``verify_runtime``. A corrupted
         retained runtime blocks the swap; verified runtimes are NEVER
         deleted by any of these operations.

    Returns the previous selector value (or None)."""
    assert setup_lock is not None, "perform_activation requires the activation lock"
    if not RUNTIME_ID_RE.fullmatch(target_id):
        raise BuilderError("state", f"invalid runtime id grammar: {target_id!r}")
    pointer = runtime_root / ACTIVE_POINTER_NAME
    current = pointer.read_text(encoding="utf-8").strip() if pointer.is_file() else ""
    if current and not RUNTIME_ID_RE.fullmatch(current):
        raise BuilderError(
            "selector",
            f"active-runtime.txt contains the invalid selector {current!r}; "
            "refusing to replace a malformed selector",
        )
    target_dir = runtime_root / VERSIONS_DIRNAME / target_id
    if not target_dir.is_dir():
        raise BuilderError(
            "state", f"{command}: runtime {target_id} does not exist under {VERSIONS_DIRNAME}/"
        )
    target_variant = _manifest_variant(target_dir)
    target_lock = lock_for_variant(target_variant)
    target_failures = [
        c
        for c in verify_runtime(target_dir, target_lock, identity, inventory, bootstrap_sha256)
        if c.code != "PASS"
    ]
    if target_failures:
        first = target_failures[0]
        raise BuilderError(
            "state",
            f"{command}: runtime {target_id} failed verification ({first.name}: {first.code}"
            + (f": {first.note}" if first.note else "")
            + "); selector not changed",
        )
    retained = current if current and current != target_id else ""
    if retained:
        retained_dir = runtime_root / VERSIONS_DIRNAME / retained
        if not retained_dir.is_dir():
            raise BuilderError(
                "state",
                f"{command}: retained runtime {retained} (previous selector) no longer exists",
            )
        retained_variant = _manifest_variant(retained_dir)
        retained_lock = lock_for_variant(retained_variant)
        retained_failures = [
            c
            for c in verify_runtime(retained_dir, retained_lock, identity, inventory, bootstrap_sha256)
            if c.code != "PASS"
        ]
        if retained_failures:
            first = retained_failures[0]
            raise BuilderError(
                "state",
                f"{command}: retained runtime {retained} failed verification "
                f"({first.name}: {first.code}"
                + (f": {first.note}" if first.note else "")
                + "); refusing to replace the selector",
            )
    return set_active_pointer(runtime_root, target_id)


def _variant_lock_loader(repo_root: Path):
    """Build the `lock_for_variant` loader used by perform_activation:
    returns the CURRENT Commit-1 artifact lock for a variant."""

    def load(variant: str) -> Lock:
        if variant not in VARIANTS:
            raise BuilderError("state", f"unknown variant {variant!r}")
        _identity, _inventory, lock, _bootstrap = load_inputs(repo_root, variant)
        return lock

    return load


