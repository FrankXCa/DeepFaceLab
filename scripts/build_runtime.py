def _offline_lock_filenames(variant: str) -> tuple[str, ...]:
    return OFFLINE_LOCK_FILES + (f"requirements-lock-{variant}.txt",)


def verify_offline_inputs(
    offline_dir: Path,
    variant: str,
    identity: PythonAsset,
    inventory: PythonLicenseInventory,
    lock: Lock,
    contract_bytes: dict[str, bytes],
) -> None:
    """Strict offline-inputs contract check.

    ``contract_bytes`` maps each Commit-1 contract filename (the three
    shared locks + the selected variant's requirements lock) to the
    AUTHORITATIVE repository bytes. The layout is usable only if it is
    COMPLETE and EXACT:

      * ``artifact-manifest.json`` exists, matches ``OFFLINE_INPUTS_SCHEMA``,
        has exactly the expected top-level field set, names this ``variant``,
        and its python block (exact field set) matches the pinned asset on
        all three fields;
      * wheel records are compared STRICTLY: every record has exactly the
        fields {filename, sha256, url, source}, no filename appears twice,
        and each record's (filename, sha256, url, source) equals the
        corresponding locked wheel record exactly - the manifest cannot
        silently re-point a wheel's URL or source while keeping filename and
        hash;
      * ``python/<archive>`` exists and hashes to the pinned asset;
      * every locked wheel is present under ``wheels/<variant>/`` with the
        locked hash (a corrupt entry is rejected, never re-fetched);
      * the Commit-1 Python license inventory is present under ``licenses/``
        with the exact installed paths and hashes, and the manifest's
        licenses/locks lists equal the contract sets exactly;
      * ``locks/`` carries all four Commit-1 contract files, and EVERY copy
        is compared BYTE-EXACT against the authoritative repository contract
        bytes (``contract_bytes``) - the layout can never be its own
        authority, so editing a lock copy (CRLF, field, hash, version) is
        detected even when the layout's manifest agrees with the edit;
      * the directory topology is EXACT: the top level is exactly
        ``python/``, ``wheels/``, ``licenses/`` and ``locks/``; under
        ``wheels/`` there is exactly the selected variant's directory - an
        empty other-variant wheel directory (invisible to the file walk) or
        any other extra/missing top-level directory is rejected (nested
        directories under ``licenses/`` mirroring the archive layout of the
        Commit-1 license paths are permitted);
      * NO file outside the exact file set may exist;
      * the offline build path has NO network capability at all
        (``OfflineFetcher`` has no opener; pip runs with ``--no-index``).

    Incomplete or malformed layouts are rejected before staging is created.
    """
    offline_dir = Path(offline_dir)
    manifest_path = offline_dir / "artifact-manifest.json"
    if not manifest_path.is_file():
        raise BuilderError(
            "offline", "offline-inputs artifact-manifest.json missing; layout incomplete"
        )
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise BuilderError(
            "offline", f"offline-inputs artifact-manifest.json unreadable: {type(exc).__name__}"
        )
    if not isinstance(manifest, dict):
        raise BuilderError("offline", "artifact-manifest must be a JSON object")
    if manifest.get("schema") != OFFLINE_INPUTS_SCHEMA:
        raise BuilderError(
            "offline", f"artifact-manifest schema mismatch: {manifest.get('schema')!r}"
        )
    if manifest.get("variant") != variant:
        raise BuilderError(
            "offline", f"artifact-manifest variant {manifest.get('variant')!r} != {variant!r}"
        )
    expected_fields = {"generated_utc", "licenses", "locks", "python", "schema", "variant", "wheels"}
    if set(manifest) != expected_fields:
        raise BuilderError(
            "offline",
            "artifact-manifest field set deviates: missing="
            + ",".join(sorted(expected_fields - set(manifest)))
            + " extra="
            + ",".join(sorted(set(manifest) - expected_fields)),
        )
    python_block = manifest.get("python", {})
    if not isinstance(python_block, dict) or set(python_block) != {"filename", "sha256", "source_url"}:
        raise BuilderError("offline", "artifact-manifest python block field set deviates")
    if (
        python_block.get("filename") != identity.filename
        or python_block.get("sha256") != identity.sha256
        or python_block.get("source_url") != identity.source_url
    ):
        raise BuilderError("offline", "artifact-manifest python block deviates from the pinned asset")
    # -- Strict wheel records: exact field set per record, no duplicate
    # filename records, and each field (sha256/url/source) compared to the
    # current lock's wheel artifacts; the record set must equal the locked
    # set.
    expected_specs = {spec.filename: spec for spec in wheel_specs(lock)}
    expected_wheel_artifacts = {w.filename: w for w in lock.wheels}
    seen_filenames: set[str] = set()
    wheels = manifest.get("wheels", [])
    if not isinstance(wheels, list):
        raise BuilderError("offline", "artifact-manifest wheels must be a list")
    for entry in wheels:
        if not isinstance(entry, dict) or set(entry) != {"filename", "sha256", "url", "source"}:
            raise BuilderError(
                "offline",
                "artifact-manifest wheel record field set deviates (need exactly filename/sha256/url/source)",
            )
        filename = entry.get("filename", "")
        if filename in seen_filenames:
            raise BuilderError("offline", f"artifact-manifest duplicate wheel record: {filename}")
        seen_filenames.add(filename)
        spec = expected_wheel_artifacts.get(filename)
        if spec is None:
            raise BuilderError("offline", f"artifact-manifest wheel record not in the lock: {filename}")
        if (
            entry.get("sha256") != spec.sha256
            or entry.get("url") != spec.url
            or entry.get("source") != spec.source
        ):
            raise BuilderError(
                "offline", f"artifact-manifest wheel record deviates from the lock: {filename}"
            )
    if seen_filenames != set(expected_specs):
        raise BuilderError(
            "offline",
            "artifact-manifest wheel set deviates from the lock (missing="
            + ",".join(sorted(set(expected_specs) - seen_filenames)[:3])
            + ")",
        )
    expected_lock_names = _offline_lock_filenames(variant)
    if sorted(manifest.get("locks", [])) != sorted(expected_lock_names):
        raise BuilderError(
            "offline",
            "artifact-manifest locks list deviates from the Commit-1 contract file set",
        )
    expected_licenses = [entry.installed_path for entry in inventory.entries]
    if sorted(manifest.get("licenses", [])) != sorted(expected_licenses):
        raise BuilderError(
            "offline", "artifact-manifest licenses list deviates from the Commit-1 inventory"
        )
    # -- Exact directory topology: the top level is EXACTLY
    # python/, wheels/, licenses/, locks/; under wheels/ there is EXACTLY
    # the selected variant's directory (an empty other-variant wheel
    # directory is rejected here - the file walk alone cannot see empty
    # directories); nested directories under licenses/ (mirroring the
    # archive layout of the Commit-1 license paths) are permitted.
    top_dirs = {p.name for p in offline_dir.iterdir() if p.is_dir()}
    expected_top = {"python", "wheels", "licenses", "locks"}
    if top_dirs != expected_top:
        raise BuilderError(
            "offline",
            "offline-inputs top-level directory set deviates: missing="
            + ",".join(sorted(expected_top - top_dirs)[:3])
            + " extra="
            + ",".join(sorted(top_dirs - expected_top)[:3]),
        )
    wheel_subdirs = {p.name for p in (offline_dir / "wheels").iterdir() if p.is_dir()}
    if wheel_subdirs != {variant}:
        raise BuilderError(
            "offline",
            f"offline-inputs wheels/ subdirectory set deviates (expected exactly "
            f"'{variant}'); found: " + ",".join(sorted(wheel_subdirs)) or "none",
        )
    python_path = offline_dir / "python" / identity.filename
    if not python_path.is_file():
        raise BuilderError("artifact-missing", f"offline-inputs/python/{identity.filename} missing")
    if locklib.sha256_file_raw(python_path) != identity.sha256:
        raise BuilderError("artifact-hash", f"offline-inputs/python/{identity.filename} failed SHA-256 verification")
    expected_wheel_hashes = {spec.filename: spec.sha256 for spec in wheel_specs(lock)}
    for filename, sha256 in sorted(expected_wheel_hashes.items()):
        path = offline_dir / "wheels" / variant / filename
        if not path.is_file():
            raise BuilderError("artifact-missing", f"offline-inputs/wheels/{variant}/{filename} missing")
        if locklib.sha256_file_raw(path) != sha256:
            raise BuilderError("artifact-hash", f"offline-inputs/wheels/{variant}/{filename} failed SHA-256 verification")
    for entry in inventory.entries:
        path = offline_dir / "licenses" / entry.installed_path
        if not path.is_file() or locklib.sha256_file_raw(path) != entry.sha256:
            raise BuilderError(
                "offline",
                f"offline-inputs/licenses/{entry.installed_path} missing or hash-mismatched "
                "(Commit-1 license inventory not reproduced exactly)",
            )
    # -- Every lock copy compared BYTE-EXACT against the authoritative
    # repository contract bytes: the layout is never its own authority.
    for name in expected_lock_names:
        path = offline_dir / "locks" / name
        if not path.is_file():
            raise BuilderError("offline", f"offline-inputs/locks/{name} missing; layout incomplete")
        authoritative = contract_bytes.get(name)
        if authoritative is None:
            raise BuilderError(
                "offline", f"no authoritative repository bytes available for locks/{name}"
            )
        if path.read_bytes() != authoritative:
            raise BuilderError(
                "offline",
                f"offline-inputs/locks/{name} is not byte-identical to the authoritative "
                "repository contract file",
            )
    allowed: set[str] = {
        "artifact-manifest.json",
        "python/" + identity.filename,
    }
    allowed |= {f"wheels/{variant}/{filename}" for filename in expected_specs}
    allowed |= {f"licenses/{entry.installed_path}" for entry in inventory.entries}
    allowed |= {f"locks/{name}" for name in expected_lock_names}
    for path in sorted(offline_dir.rglob("*")):
        if path.is_dir():
            continue
        rel = path.relative_to(offline_dir).as_posix()
        if rel not in allowed:
            raise BuilderError("offline", f"unexpected file in offline-inputs: {rel}")


def write_offline_inputs(
    output_dir: Path,
    variant: str,
    identity: PythonAsset,
    inventory: PythonLicenseInventory,
    lock: Lock,
    fetcher: object,
    lock_files: list[Path],
    log=print,
) -> None:
    """Materialize the offline-inputs layout from one fetcher.

    Layout (exactly what ``verify_offline_inputs`` requires, and nothing
    else): python/<archive>, wheels/<variant>/<wheel>, licenses/<installed
    relative paths from the Commit-1 inventory>, locks/<contract files>,
    artifact-manifest.json. The caller decides where the artifacts come from
    (online cache or an existing directory); this function only verifies and
    copies. The generated directory is re-validated with the strict contract
    before the function returns, so ``fetch-offline-inputs`` always produces
    a layout that ``build --offline`` will accept.
    """
    validate_variant(variant)
    output_dir = Path(output_dir)
    (output_dir / "python").mkdir(parents=True, exist_ok=True)
    (output_dir / "wheels" / variant).mkdir(parents=True, exist_ok=True)
    (output_dir / "licenses").mkdir(parents=True, exist_ok=True)
    (output_dir / "locks").mkdir(parents=True, exist_ok=True)

    log(f"fetching Python archive: {identity.filename}")
    archive = fetcher.fetch(python_spec(identity))
    shutil.copy2(archive, output_dir / "python" / identity.filename)
    # License files from the pinned archive, kept under their installed
    # relative paths (the Commit-1 inventory's installed paths).
    with tarfile.open(archive, mode="r:gz") as package:
        for member in package.getmembers():
            if not member.isfile():
                continue
            relative = PurePosixPath(member.name)
            if relative.parts and not locklib.license_path_matches(relative):
                continue
            stream = package.extractfile(member)
            if stream is None:
                continue
            installed_relative = member.name[len(PYTHON_ARCHIVE_ROOT) + 1 :]
            destination = output_dir / "licenses" / installed_relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            with stream:
                destination.write_bytes(stream.read())
    for spec in wheel_specs(lock):
        log(f"fetching wheel: {spec.filename}")
        path = fetcher.fetch(spec)
        shutil.copy2(path, output_dir / "wheels" / variant / spec.filename)

    for source in lock_files:
        shutil.copy2(source, output_dir / "locks" / source.name)

    manifest = {
        "generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "licenses": [entry.installed_path for entry in inventory.entries],
        "locks": [name for name in _offline_lock_filenames(variant)],
        "python": {
            "filename": identity.filename,
            "sha256": identity.sha256,
            "source_url": identity.source_url,
        },
        "schema": OFFLINE_INPUTS_SCHEMA,
        "variant": variant,
        "wheels": [
            {
                "filename": spec.filename,
                "sha256": spec.sha256,
                "source": next(w.source for w in lock.wheels if w.filename == spec.filename),
                "url": spec.url,
            }
            for spec in wheel_specs(lock)
        ],
    }
    scan_privacy(json.dumps(manifest, sort_keys=True), "artifact-manifest.json")
    (output_dir / "artifact-manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    # Final strict validation: the generated layout's lock copies are
    # compared byte-exact against the authoritative repository contract
    # bytes (the source files themselves).
    verify_offline_inputs(
        output_dir,
        variant,
        identity,
        inventory,
        lock,
        {path.name: path.read_bytes() for path in lock_files},
    )
    log(f"offline-inputs ready: {output_dir.name}/python, wheels/{variant}, licenses, locks")


def fetch_offline_inputs(
    repo_root: Path,
    variant: str,
    output_dir: Path,
    cache_dir: Path,
    log=print,
) -> None:
    """CLI-level wrapper: load the Commit-1 contract and prepare offline
    inputs from the exact online sources into one directory."""
    validate_variant(variant)
    identity, inventory, lock, _bootstrap = load_inputs(repo_root, variant)
    fetcher = OnlineFetcher(cache_dir, variant)
    lock_files = [repo_root / name for name in _offline_lock_filenames(variant)]
    write_offline_inputs(output_dir, variant, identity, inventory, lock, fetcher, lock_files, log)


