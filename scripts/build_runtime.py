class BuildContext:
    repo_root: Path
    runtime_root: Path
    identity: PythonAsset
    inventory: PythonLicenseInventory
    lock: Lock
    bootstrap_sha256: str
    fetcher: object  # OnlineFetcher | OfflineFetcher
    installer: object  # SubprocessPipInstaller or a test double
    interpreter: object  # SubprocessInterpreter or a test double
    activate: bool = False
    lock_timeout: float = 3600.0
    log: object = print  # callable(str)
    # Offline mode: the AUTHORITATIVE repository bytes of the four Commit-1
    # contract files (the three shared locks + this variant's requirements
    # lock), keyed by filename. When None (and the fetcher is offline),
    # run_build loads them from repo_root. The offline layout's copies are
    # compared BYTE-EXACT against these bytes; the layout can never be its
    # own authority.
    offline_contract_bytes: dict[str, bytes] | None = None
    # Variant -> current Commit-1 lock loader for perform_activation (it must
    # fully verify the target AND the retained runtime, which may be a
    # different variant). When None, run_build loads locks from repo_root.
    # Tests inject a double that knows the fake locks of the variants
    # involved.
    lock_loader: object = None


def _log(ctx: BuildContext, message: str) -> None:
    ctx.log(message)


def _fail(ctx: BuildContext, code: str, message: str) -> None:
    _log(ctx, f"FAIL [{code}] {message}")
    raise BuilderError(code, message)


def _probe_distributions(ctx: BuildContext, python_exe: Path, cwd: Path) -> tuple[dict[str, set[str]], dict[str, str]]:
    try:
        proc = ctx.interpreter.run(python_exe, "-c", DISTRIBUTIONS_SCRIPT, cwd=cwd, timeout=300)
    except Exception as exc:  # noqa: BLE001
        _fail(ctx, "interpreter", f"distributions probe failed: {type(exc).__name__}")
    if proc.returncode != 0:
        _fail(ctx, "interpreter", "distributions probe exited " + str(proc.returncode))
    raw = json.loads(proc.stdout.strip())
    return distributions_from_probe(raw)


def run_build(ctx: BuildContext) -> BuildResult:
    started = time.monotonic()
    started_utc = datetime.now(timezone.utc)
    notes: list[str] = []
    identity, inventory, lock = ctx.identity, ctx.inventory, ctx.lock
    # The final runtime ID binds the installed-tree integrity digest, which
    # only exists after installation and normalization; it is computed below
    # (and logged) once the tree exists. The candidate is staged under a
    # temporary name until then.
    runtime_id = ""

    versions_dir = ctx.runtime_root / VERSIONS_DIRNAME
    staging_root = ctx.runtime_root / STAGING_DIRNAME

    setup_lock = SetupActivationLock(ctx.runtime_root, ctx.lock_timeout).acquire()
    staging_dir = None
    try:
        # -- Offline contract: the COMPLETE approved layout must validate
        # before any staging exists (defense in depth on top of the CLI
        # check). The layout's lock copies are compared BYTE-EXACT against
        # the authoritative repository contract bytes (never against the
        # layout's own bytes). OfflineFetcher has no network capability by
        # construction.
        if isinstance(ctx.fetcher, OfflineFetcher):
            if ctx.offline_contract_bytes is None:
                ctx.offline_contract_bytes = {
                    name: (ctx.repo_root / name).read_bytes()
                    for name in _offline_lock_filenames(lock.variant)
                }
            verify_offline_inputs(
                ctx.fetcher.offline_dir,
                lock.variant,
                identity,
                inventory,
                lock,
                ctx.offline_contract_bytes,
            )
            _log(ctx, "offline-inputs layout validated (complete, exact, byte-anchored to the repository contract, no network path)")
        staging_root.mkdir(parents=True, exist_ok=True)
        for stale in sorted(staging_root.iterdir()):
            if stale.is_dir():
                _log(ctx, f"cleaning stale staging candidate {stale.name}")
                shutil.rmtree(stale)
        nonce = secrets.token_hex(4)
        staging_dir = staging_root / f"candidate-{nonce}"
        staging_dir.mkdir(parents=True)
        staged_python = staging_dir / "python.exe"

        # -- Python asset: verify raw archive SHA-256 BEFORE extraction.
        archive_path = ctx.fetcher.fetch(python_spec(identity))
        if locklib.sha256_file_raw(archive_path) != identity.sha256:
            _fail(ctx, "artifact-hash", "Python archive failed SHA-256 verification before extraction")
        _log(ctx, f"Python archive verified: {identity.filename}")

        extract_python_archive(archive_path, staging_dir)
        _log(ctx, "standalone Python extracted into staging")

        license_checks = check_python_license_tree(staging_dir, inventory, identity)
        if license_checks[0].code != "PASS":
            _fail(ctx, "license", license_checks[0].note or "Python license inventory verification failed")

        baseline, _baseline_dist = _probe_distributions(ctx, staged_python, staging_dir)
        _log(ctx, f"interpreter baseline: {len(baseline)} bundled distributions")

        # -- Baseline authority: capture the authoritative digest
        #    inventory for the bundled-distribution files IMMEDIATELY,
        #    while the tree is still exactly the verified pinned
        #    archive's extraction - before wheel installation, before
        #    any pip invocation, and before any normalization. This
        #    captured state (never post-install staging bytes) is the
        #    sole authority for baseline RECORD reconciliation later.
        baseline_authority = capture_baseline_authority(staging_dir, _baseline_dist)
        _log(
            ctx,
            f"baseline authority captured: "
            f"{sum(len(v['paths']) for v in baseline_authority.values())} baseline RECORD paths "
            f"({sum(len(v['files']) for v in baseline_authority.values())} files) "
            "from the verified archive (pre-install)",
        )

        # -- Wheel acquisition (hash-verified) immediately before installation.
        wheel_files: dict[str, Path] = {}
        for spec in wheel_specs(lock):
            wheel_files[spec.filename] = ctx.fetcher.fetch(spec)
        _log(ctx, f"{len(wheel_files)} locked wheels verified")

        # -- No-resolution install into the staged runtime's own Python.
        requirements_text = _render_requirements(lock, wheel_files)
        req_handle = tempfile.NamedTemporaryFile(
            "w", delete=False, suffix=".txt", encoding="utf-8", newline="\n",
            prefix="dfl-requirements-",
        )
        try:
            req_handle.write(requirements_text)
            req_handle.close()
            ctx.installer.install(
                staged_python,
                Path(req_handle.name),
                staging_dir,
                ctx.runtime_root / STAGING_DIRNAME / "pip-cache",
            )
        finally:
            try:
                os.unlink(req_handle.name)
            except OSError:
                pass
        _log(ctx, "locked wheels installed (no resolution)")

        installed, dist_info_map = _probe_distributions(ctx, staged_python, staging_dir)

        checks: list[Check] = []
        checks.extend(license_checks)

        set_checks = verify_package_set(installed, baseline, lock)
        checks.extend(set_checks)
        if set_checks[0].code != "PASS":
            _fail(ctx, "package_set", set_checks[0].note or "installed package set deviates from the lock")
        variant_checks = verify_variant_contract(installed, lock)
        checks.extend(variant_checks)
        if variant_checks[0].code != "PASS":
            _fail(ctx, "variant", variant_checks[0].note or "variant contract violated")

        # -- Basic import validation using the ASSEMBLED portable Python.
        modules = list(COMMON_IMPORT_MODULES) + (list(GUI_IMPORT_MODULES) if lock.gui else [])
        try:
            proc = ctx.interpreter.run(
                staged_python, "-c", IMPORTS_SCRIPT_TEMPLATE.format(modules=modules),
                cwd=staging_dir, timeout=900,
            )
        except Exception as exc:  # noqa: BLE001
            _fail(ctx, "imports", f"import validation failed: {type(exc).__name__}")
        if proc.returncode != 0:
            _fail(ctx, "imports", "import validation exited " + str(proc.returncode))
        import_report = json.loads(proc.stdout.strip())
        executable = Path(import_report.get("executable", ""))
        try:
            executable.resolve().relative_to(staging_dir.resolve())
        except ValueError:
            _fail(ctx, "python_identity", "sys.executable does not point into the assembled runtime")
        if not import_report.get("isolated") or not import_report.get("dont_write_bytecode"):
            _fail(ctx, "python_identity", "assembled interpreter ran without isolation flags")
        import_failures = {m: r for m, r in import_report.get("modules", {}).items() if r != "ok"}
        if import_failures:
            _fail(ctx, "imports", "module import failures: " + "; ".join(f"{m} ({r})" for m, r in list(import_failures.items())[:3]))
        checks.append(Check("imports", "PASS", f"{len(modules)} modules imported"))
        checks.append(Check("python_identity", "PASS"))

        # -- Isolated bootstrap self-test (runtime_entry.py).
        entry_path = ctx.repo_root / BOOTSTRAP_RELATIVE
        if not entry_path.is_file():
            _fail(ctx, "bootstrap", "missing scripts/runtime_entry.py")
        try:
            proc = ctx.interpreter.run(staged_python, str(entry_path), "--self-test", cwd=staging_dir, timeout=120)
        except Exception as exc:  # noqa: BLE001
            _fail(ctx, "bootstrap", f"runtime_entry self-test failed: {type(exc).__name__}")
        if proc.returncode != 0:
            _fail(ctx, "bootstrap", "runtime_entry self-test exited " + str(proc.returncode))
        self_test = json.loads(proc.stdout.strip())
        if not self_test.get("ok") or not self_test.get("isolated") or not self_test.get("dont_write_bytecode"):
            _fail(ctx, "bootstrap", "runtime_entry self-test reported a non-isolated interpreter")
        if Path(self_test.get("executable", "")).resolve() != staged_python.resolve():
            _fail(ctx, "bootstrap", "runtime_entry self-test used an unexpected interpreter")
        checks.append(Check("runtime_entry_self_test", "PASS"))

        # -- Torch boundary: package identity always; hardware state reported,
        # never required, for a CUDA build. The hardware state is recorded in
        # OPERATIONAL data only: it must never alter the canonical manifest.
        torch_hardware: dict | None = None
        if lock.variant.startswith("cuda"):
            try:
                # CWD is the staging ROOT (a sibling of the candidate), not the
                # candidate itself: initializing CUDA on a GPU host can make
                # the NVIDIA driver create CWD-relative state (e.g. NVSTCache),
                # which must never be able to land inside the tree that is
                # about to be promoted.
                proc = ctx.interpreter.run(staged_python, "-c", TORCH_PROBE_SCRIPT, cwd=staging_root, timeout=900)
            except Exception as exc:  # noqa: BLE001
                _fail(ctx, "torch_probe", f"torch probe failed: {type(exc).__name__}")
            if proc.returncode != 0:
                _fail(ctx, "torch_probe", "torch probe exited " + str(proc.returncode))
            probe = json.loads(proc.stdout.strip())
            if not probe.get("imported"):
                _fail(ctx, "torch_probe", "torch import failed in the assembled runtime")
            if probe.get("version") != lock.package_set.get("torch"):
                _fail(ctx, "torch_probe", "torch version mismatch in the assembled runtime")
            expected_line = EXPECTED_CUDA_LINE.get(lock.torch_backend)
            if expected_line and probe.get("cuda_built") != expected_line:
                _fail(ctx, "torch_probe", f"expected CUDA line {expected_line}, got {probe.get('cuda_built')}")
            if probe.get("cuda_available") is True:
                checks.append(Check("torch_probe", "PASS", "cuda line verified; physical device present"))
                notes.append("torch.cuda.is_available(): true")
                torch_hardware = {
                    "code": "PASS",
                    "cuda_available": True,
                    "cuda_built": probe.get("cuda_built"),
                    "device": probe.get("device"),
                }
            else:
                checks.append(
                    Check("torch_probe", "ENVIRONMENTALLY_LIMITED", "cuda line verified; no usable device on this host")
                )
                notes.append("torch.cuda.is_available(): false (build remains valid)")
                torch_hardware = {
                    "code": "ENVIRONMENTALLY_LIMITED",
                    "cuda_available": False,
                    "cuda_built": probe.get("cuda_built"),
                    "device": None,
                }
        else:
            checks.append(Check("torch_probe", "NOT_APPLICABLE", "cpu variant"))
            torch_hardware = {
                "code": "NOT_APPLICABLE",
                "cuda_available": None,
                "cuda_built": None,
                "device": None,
            }

        # -- Bytecode policy, launcher contract, provenance normalization,
        #    prohibited cache classes. No bulk archive deletion: only the
        #    exact reviewed scipy self-copy is recognized (kept, documented),
        #    only direct_url.json provenance pointers are removed (with their
        #    RECORD lines), and only the pip console launcher binaries are
        #    removed (entry points recorded semantically in the manifest).
        scrubbed = scrub_generated_bytecode(staging_dir)
        if scrubbed:
            notes.append(f"removed {scrubbed} generated bytecode artifacts")
        removed_launchers = remove_pip_launchers(staging_dir)
        if removed_launchers:
            notes.append(
                f"removed {len(removed_launchers)} pip console launcher binaries "
                "(not byte-reproducible; entry points recorded in the manifest, "
                "invoked via the runtime's own interpreter)"
            )
        removed_direct_url = normalize_installed_records(staging_dir)
        if removed_direct_url:
            notes.append(
                f"removed {len(removed_direct_url)} direct_url.json provenance pointers "
                "(matching RECORD lines dropped to keep RECORD self-consistent)"
            )
        dropped_records = drop_noncanonical_record_lines(staging_dir)
        if dropped_records:
            notes.append(
                f"dropped {dropped_records} RECORD entries for scrubbed generated "
                "bytecode and removed launcher binaries (RECORD kept "
                "self-consistent with the tree)"
            )
        console_scripts = collect_console_scripts(staging_dir)
        normalizations: list[dict] = []
        if removed_launchers:
            normalizations.append(
                {
                    "type": "pip-launchers",
                    "paths": removed_launchers,
                    "action": "launcher binaries removed; console-script entry points recorded in the manifest",
                }
            )
        if removed_direct_url:
            normalizations.append(
                {
                    "type": "direct-url",
                    "paths": removed_direct_url,
                    "action": "file removed; RECORD entry dropped",
                }
            )
        if dropped_records:
            normalizations.append(
                {
                    "type": "bytecode-records",
                    "lines_dropped": dropped_records,
                    "action": "RECORD entries of scrubbed .pyc/__pycache__ files and removed launchers dropped",
                }
            )
        # -- Baseline RECORD reconciliation against the CAPTURED
        #    pre-install authority. Post-install modification of any
        #    baseline file or RECORD entry is rejected fail-closed,
        #    EXCEPT the reviewed exception set (pinned archive's bundled
        #    pip distlib executable normalization), which may only
        #    re-anchor its hash/size fields to the captured archive
        #    bytes. No generic normalization of baseline bytes exists.
        reanchored, authority_violations = reconcile_baseline_records(
            staging_dir, baseline_authority, _baseline_dist
        )
        if authority_violations:
            _fail(
                ctx,
                "baseline_authority",
                "baseline RECORD reconciliation rejected (post-install baseline "
                "modification is never normalized): "
                + "; ".join(authority_violations[:5]),
            )
        if reanchored:
            touched_total = sum(len(v) for v in reanchored.values())
            normalizations.append(
                {
                    "type": "baseline-record-reanchor",
                    "distributions": reanchored,
                    "action": (
                        "RECORD hash/size entries of the bundled (interpreter-baseline) "
                        "distribution re-anchored from the CAPTURED pre-install baseline "
                        "authority (the verified archive's bytes, captured before "
                        "installation) within the reviewed exception set only (pinned "
                        "archive's bundled pip distlib executable normalization); every "
                        "other baseline file/RECORD entry was verified byte-exact "
                        "against the captured authority and any other modification "
                        "fails the build closed"
                    ),
                }
            )
            notes.append(
                f"re-anchored {touched_total} baseline RECORD hash entries to the "
                "captured pre-install archive bytes (reviewed exception set only; "
                "all other baseline bytes verified unmodified against the capture)"
            )
        scipy_exception = normalize_scipy_self_copy(staging_dir)
        if scipy_exception is not None:
            normalizations.append(scipy_exception)
            notes.append(
                "recognized exact scipy 1.18.1 self-copy artifact at "
                f"{scipy_exception['path']} (upstream wheel defect; retained, "
                "excluded from canonical identity)"
            )
        remaining_pyc = [p.name for p in staging_dir.rglob("*.pyc")]
        cache_violations = scan_prohibited(staging_dir)
        if remaining_pyc or cache_violations:
            _fail(ctx, "prohibited_cache", "prohibited artifacts remain: " + "; ".join((remaining_pyc + cache_violations)[:5]))
        checks.append(Check("bytecode_policy", "PASS"))
        checks.append(Check("prohibited_cache", "PASS"))

        # -- Installed-tree inventory over the fully normalized tree:
        # per-distribution consistency digests + the canonical integrity
        # digest over the ACTUAL bytes of every file (anchors the runtime ID).
        tree_inventory = build_installed_tree_inventory(
            staging_dir, lock.package_set, dist_info_map
        )
        checks.append(Check("installed_tree", "PASS"))

        # -- The runtime ID is now known (it binds the tree digest).
        runtime_id = compute_runtime_id(
            ctx.bootstrap_sha256, identity, inventory, lock,
            tree_inventory["inventory_sha256"],
        )
        _log(ctx, f"runtime id {runtime_id} (variant {lock.variant})")

        # -- Manifest: canonical identity + operational notes, privacy-scanned.
        manifest = build_manifest(
            runtime_id, identity, inventory, lock, ctx.bootstrap_sha256,
            baseline, tree_inventory, checks, started_utc,
            time.monotonic() - started, notes,
            torch_hardware=torch_hardware, normalizations=normalizations,
            console_scripts=console_scripts,
        )
        write_manifest(staging_dir / MANIFEST_NAME, manifest)
        checks.append(Check("manifest_privacy", "PASS"))
        _log(ctx, "manifest written and privacy-scanned")

        # -- Atomic promotion (or verified reuse), then FULL verification
        #    against the PROMOTED path with the current Commit-1 inputs.
        versions_dir.mkdir(parents=True, exist_ok=True)
        target = versions_dir / runtime_id
        if target.exists():
            existing = verify_runtime(target, lock, identity, inventory, ctx.bootstrap_sha256)
            if all(item.code == "PASS" for item in existing):
                shutil.rmtree(staging_dir)
                staging_dir = None
                state = "REUSED"
                notes.append("existing identical runtime verified and reused")
            else:
                first = next((c for c in existing if c.code != "PASS"), None)
                _fail(
                    ctx, "state",
                    f"existing runtime {runtime_id} does not match the expected contract "
                    f"({first.code if first else 'unknown'}); refusing to modify it",
                )
        else:
            os.replace(staging_dir, target)
            staging_dir = None
            state = "BUILT"
        _log(ctx, f"runtime {state.lower()}: versions/{runtime_id}")

        post_checks = verify_runtime(target, lock, identity, inventory, ctx.bootstrap_sha256)
        post_failures = [c for c in post_checks if c.code != "PASS"]
        if post_failures:
            first = post_failures[0]
            # Non-destructive: the candidate is left in place for inspection,
            # it is NOT reported BUILT and it is NOT activated; the active
            # pointer is untouched.
            _fail(
                ctx,
                "post-promotion-verify",
                f"runtime {runtime_id} failed FULL verification against the "
                f"promoted path ({first.name}: {first.code}"
                + (f": {first.note}" if first.note else "")
                + "); the candidate is left in place, NOT reported built and NOT activated",
            )
        checks.extend(post_checks)
        _log(ctx, f"post-promotion verification: {len(post_checks)} checks, all PASS")

        activated = False
        if ctx.activate:
            # Post-promotion activation: the promoted (or reused) runtime has
            # just passed the full corrected verify_runtime above;
            # perform_activation re-runs it for the target AND fully verifies
            # the retained runtime with its OWN variant's current Commit-1
            # lock, validates the selector grammar, and only then swaps the
            # pointer - all under the same held activation lock. Verified
            # runtimes are never deleted by activation.
            loader = ctx.lock_loader if ctx.lock_loader is not None else _variant_lock_loader(ctx.repo_root)
            try:
                previous = perform_activation(
                    ctx.runtime_root,
                    runtime_id,
                    identity,
                    inventory,
                    ctx.bootstrap_sha256,
                    loader,
                    setup_lock,
                    "build",
                )
            except BuilderError as exc:
                _fail(ctx, exc.code, exc.message)
            activated = True
            notes.append(
                f"active pointer set (previous: {previous if previous else 'none'})"
            )
            _log(ctx, f"active-runtime pointer -> {runtime_id}")

        return BuildResult(
            runtime_id=runtime_id,
            state=state,
            runtime_dir=target,
            activated=activated,
            checks=tuple(checks),
        )
    finally:
        setup_lock.release()
        if staging_dir is not None and staging_dir.exists():
            # Failed/unverified staging may remain for inspection; the next
            # build (holding the same lock) cleans it before starting.
            pass


def _render_requirements(lock: Lock, wheel_files: dict[str, Path]) -> str:
    """Requirements file for the no-resolution install: exact locked local
    wheel files plus their locked SHA-256 hashes, nothing else."""
    lines: list[str] = []
    for wheel in sorted(lock.wheels, key=lambda w: w.name):
        lines.append(f"{wheel.name} @ {wheel_files[wheel.filename].as_uri()} \\")
        lines.append(f"    --hash=sha256:{wheel.sha256}")
    return "\n".join(lines) + "\n"


