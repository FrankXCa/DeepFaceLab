def verify_package_set(
    installed: dict[str, set[str]],
    baseline: dict[str, set[str]],
    lock: Lock,
) -> list[Check]:
    expected: dict[str, set[str]] = {name: set(versions) for name, versions in baseline.items()}
    for name, version in lock.package_set.items():
        expected.setdefault(name, set()).add(version)
    problems: list[str] = []
    for name in sorted(set(installed) | set(expected)):
        have = installed.get(name, set())
        want = expected.get(name, set())
        if have != want:
            problems.append(
                f"{name}: installed={sorted(have) or 'absent'} expected={sorted(want) or 'absent'}"
            )
    if problems:
        return [Check("package_set", "MISMATCH", "; ".join(problems[:4]))]
    return [Check("package_set", "PASS", f"{len(expected)} distributions exact")]


def verify_variant_contract(installed: dict[str, set[str]], lock: Lock) -> list[Check]:
    problems: list[str] = []
    if lock.gui:
        for name in GUI_PACKAGE_FAMILY:
            if name not in installed:
                problems.append(f"GUI variant missing {name}")
    else:
        for name in GUI_PACKAGE_FAMILY:
            if name in installed:
                problems.append(f"no-GUI variant must not contain {name}")
    torch_versions = installed.get("torch", set())
    if len(torch_versions) != 1:
        problems.append(f"torch must resolve to exactly one version, got {sorted(torch_versions)}")
    else:
        version = next(iter(torch_versions))
        if lock.torch_backend == "cpu" and not version.endswith("+cpu"):
            problems.append(f"CPU variant requires torch +cpu build, got {version}")
        elif lock.torch_backend == "cu130" and not version.endswith("+cu130"):
            problems.append(f"CUDA variant requires torch +cu130 build, got {version}")
    if problems:
        return [Check("variant_contract", "MISMATCH", "; ".join(problems))]
    return [Check("variant_contract", "PASS", lock.variant)]


def scrub_generated_bytecode(runtime_dir: Path) -> int:
    removed = 0
    for dirpath, dirnames, filenames in os.walk(runtime_dir, topdown=False):
        for dirname in list(dirnames):
            if dirname == "__pycache__":
                shutil.rmtree(os.path.join(dirpath, dirname))
                removed += 1
        for filename in filenames:
            if filename.endswith(".pyc"):
                os.unlink(os.path.join(dirpath, filename))
                removed += 1
    return removed


def _under_ensurepip(runtime_dir: Path, path: Path) -> bool:
    try:
        parts = path.relative_to(runtime_dir).parts
    except ValueError:
        return False
    return (
        len(parts) >= 2
        and parts[0].casefold() == "lib"
        and parts[1].casefold() == "ensurepip"
    )


def scan_prohibited(runtime_dir: Path) -> list[str]:
    """Prohibited cache classes, matched case-insensitively (Windows/NTFS is
    case-preserving but not case-sensitive, e.g. NVIDIA's mixed-case
    NVSTCache).

    Three documented exemptions:

    * the interpreter's own ``Lib/ensurepip/`` tree: part of the pinned
      standalone archive (SHA-256-locked, including its bundled pip wheel),
      i.e. interpreter distribution content, not an install byproduct;
    * the exact reviewed scipy 1.18.1 self-copy artifact, and ONLY when every
      invariant in ``SCIPY_SELF_COPY`` holds (see
      ``normalize_scipy_self_copy``);
    * nothing under ``Scripts/`` is exempt: a promoted runtime carries NO
      launcher binaries (see the launcher contract in
      ``remove_pip_launchers``), so ANY file or directory under ``Scripts/``
      in a promoted tree is an integrity violation (planted or surviving
      launcher).

    Any other archive-shaped file (``.whl``/``.zip``/``.tar``/...) anywhere
    in the tree is reported unmodified: nothing is deleted and the build
    fails closed."""
    violations: list[str] = []
    scipy_target = runtime_dir / SCIPY_SELF_COPY["relative_path"]
    scripts_dir = runtime_dir / "Scripts"
    if scripts_dir.exists():
        detail = sorted(
            p.relative_to(runtime_dir).as_posix()
            for p in scripts_dir.rglob("*")
            if p.is_file()
        )
        violations.append(
            "unexpected Scripts/ directory (launcher binaries are not shipped"
            + (f"; files: {', '.join(detail[:3])}" if detail else "")
            + ")"
        )
    for path in sorted(runtime_dir.rglob("*")):
        if path.is_dir():
            if path.name.casefold() in PROHIBITED_DIR_NAMES:
                violations.append(f"directory {path.name}")
            continue
        if path.suffix == ".pyc":
            violations.append(path.name)
        elif PROHIBITED_ARCHIVE_RE.search(path.name):
            if _under_ensurepip(runtime_dir, path):
                continue
            if path == scipy_target:
                if _scipy_self_copy_valid(runtime_dir):
                    continue
                violations.append(
                    f"unexpected archive file {path.name}: does not match the exact "
                    "scipy 1.18.1 self-copy invariants"
                )
                continue
            violations.append(path.name)
    return violations


def _record_entry_path(line: str) -> str:
    """The file path component of a RECORD line (quotes stripped)."""
    return line.split(",", 1)[0].strip().strip('"')


def _scipy_self_copy_valid(runtime_dir: Path) -> bool:
    """True iff the scipy self-copy artifact at the exact documented path
    satisfies EVERY invariant in ``SCIPY_SELF_COPY``: distribution/version
    (encoded in the path), zero-byte size, SHA-256 of empty content, and the
    matching RECORD entry in scipy's dist-info."""
    target = runtime_dir / SCIPY_SELF_COPY["relative_path"]
    if not target.is_file():
        return False
    if target.stat().st_size != SCIPY_SELF_COPY["size"]:
        return False
    if locklib.sha256_file_raw(target) != SCIPY_SELF_COPY["record_sha256_hex"]:
        return False
    record = runtime_dir / "Lib" / "site-packages" / "scipy-1.18.1.dist-info" / "RECORD"
    if not record.is_file():
        return False
    expected = f"sha256={SCIPY_SELF_COPY['record_sha256_b64']}"
    for raw in record.read_text(encoding="utf-8").splitlines():
        if not raw:
            continue
        if _record_entry_path(raw) != SCIPY_SELF_COPY["filename"]:
            continue
        if raw.split(",")[1:2] == [expected]:
            return True
    return False


def normalize_scipy_self_copy(runtime_dir: Path) -> dict | None:
    """Recognize the exact reviewed SciPy 1.18.1 self-copy defect.

    The builder performs NO bulk deletion of archive-looking files. The one
    documented exception is the exact artifact described by
    ``SCIPY_SELF_COPY`` (an upstream wheel-packaging defect: the scipy 1.18.1
    win_amd64 wheel bundles a zero-byte file named after the wheel itself,
    which pip installs into ``Lib/site-packages/``). That file is KEPT in the
    tree (it is part of the RECORD-verified payload and is zero bytes); it is
    excluded from the canonical RECORD identity and the exception is recorded
    in the operational manifest.

    If a file exists at the exact path but fails ANY invariant, or any OTHER
    archive-shaped file exists in the tree, nothing is normalized here: the
    prohibited-cache scan fails the build (fail closed).
    """
    target = runtime_dir / SCIPY_SELF_COPY["relative_path"]
    if not target.exists():
        return None
    if not _scipy_self_copy_valid(runtime_dir):
        raise BuilderError(
            "prohibited-cache",
            f"archive file at {SCIPY_SELF_COPY['relative_path']} does not match the exact "
            "scipy 1.18.1 self-copy invariants (distribution/version, zero-byte size, "
            "empty-content SHA-256, RECORD entry); refusing to normalize it",
        )
    return {
        "type": "scipy-self-copy",
        "distribution": SCIPY_SELF_COPY["distribution"],
        "version": SCIPY_SELF_COPY["version"],
        "path": SCIPY_SELF_COPY["relative_path"],
        "size": SCIPY_SELF_COPY["size"],
        "sha256": SCIPY_SELF_COPY["record_sha256_hex"],
        "action": "recognized and retained; excluded from canonical RECORD identity",
    }


def normalize_installed_records(runtime_dir: Path) -> list[str]:
    """Remove pip's ``direct_url.json`` provenance pointers and keep the
    on-disk RECORD self-consistent.

    ``direct_url.json`` (written by pip into the dist-info of direct-URL
    installs) records the build machine's artifact-cache path
    (``file://...``): build-local provenance that is dangling on any other
    machine and a privacy leak in a frozen, relocatable runtime. For every
    dist-info that has one, the file is removed AND its RECORD entry is
    dropped, so every remaining RECORD entry references a file that exists.

    Returns the removed file paths (runtime-root-relative, POSIX), sorted."""
    removed: list[str] = []
    site = runtime_dir / "Lib" / "site-packages"
    if not site.is_dir():
        return removed
    for dist_dir in sorted(
        p for p in site.iterdir() if p.is_dir() and p.name.endswith(".dist-info")
    ):
        direct_url = dist_dir / "direct_url.json"
        if not direct_url.is_file():
            continue
        direct_url.unlink()
        record = dist_dir / "RECORD"
        if record.is_file():
            entry_name = f"{dist_dir.name}/direct_url.json"
            lines = [
                ln
                for ln in record.read_text(encoding="utf-8").splitlines()
                if ln and _record_entry_path(ln) != entry_name
            ]
            record.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        removed.append(f"Lib/site-packages/{dist_dir.name}/direct_url.json")
    removed.sort()
    return removed


def collect_console_scripts(runtime_dir: Path) -> dict[str, str]:
    """Collect the console-script entry points declared by the installed
    distributions (``entry_points.txt`` / ``[console_scripts]`` in each
    dist-info), as {script name: "module:function" or "module"}.

    This is the deterministic, wheel-derived SEMANTIC record of what pip
    would have exposed as ``Scripts/*.exe`` launchers. The launcher binaries
    are not shipped (they embed build-machine paths and are not
    byte-reproducible); entry points are invoked via the runtime's own
    interpreter (``python -I -B -m <module>`` / scripts/runtime_entry.py).
    """
    scripts: dict[str, str] = {}
    site = runtime_dir / "Lib" / "site-packages"
    if not site.is_dir():
        return scripts
    for dist_dir in sorted(
        p for p in site.iterdir() if p.is_dir() and p.name.endswith(".dist-info")
    ):
        eps = dist_dir / "entry_points.txt"
        if not eps.is_file():
            continue
        in_section = False
        for line in eps.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line:
                continue
            if line.startswith("[") and line.endswith("]"):
                in_section = line.strip("[]").lower() == "console_scripts"
                continue
            if in_section and "=" in line:
                name, value = (part.strip() for part in line.split("=", 1))
                if name:
                    scripts[name] = value
    return scripts


def remove_pip_launchers(runtime_dir: Path) -> list[str]:
    """Remove the pip-generated ``Scripts/*.exe`` console launcher binaries
    (and any other files under ``Scripts/``) from the tree.

    Launcher binaries embed build-machine paths (the staged interpreter
    location) and are therefore NOT byte-reproducible across equivalent
    builds; shipping them would either break canonical reproducibility or
    force a non-portable integrity anchor. The trusted contract is instead:
    the console-script ENTRY POINTS are recorded deterministically in the
    manifest (``console_scripts``, from the locked wheels' metadata) and are
    invoked through the runtime's own interpreter. A promoted runtime
    therefore contains NO files under ``Scripts/``; the prohibited-cache
    scan treats any file (or directory) under ``Scripts/`` as an integrity
    violation, so post-build launcher tampering or planting cannot be
    hidden (the mutable-RECORD launcher vector is removed at the same time:
    launcher RECORD lines are dropped by
    ``drop_noncanonical_record_lines``).
    """
    scripts = runtime_dir / "Scripts"
    removed: list[str] = []
    if scripts.is_dir():
        for path in sorted(scripts.iterdir()):
            if path.is_file():
                removed.append("Scripts/" + path.name)
                path.unlink()
        if not any(scripts.iterdir()):
            shutil.rmtree(scripts)
    return removed


def drop_noncanonical_record_lines(runtime_dir: Path) -> int:
    """Drop RECORD entries whose files the builder deliberately does not
    carry in the promoted tree, keeping every on-disk RECORD self-consistent
    (every remaining entry references a file that exists, with exact
    recorded bytes):

      * generated bytecode (``*.pyc`` / ``__pycache__``) - scrubbed from the
        tree by ``scrub_generated_bytecode``;
      * pip console-script launcher entries (``../../Scripts/*.exe``) - the
        launcher binaries are removed by ``remove_pip_launchers`` (they are
        not byte-reproducible; the semantic entry points are recorded in the
        manifest instead).

    A ``.pyc`` or a file under ``Scripts/`` re-appearing in a promoted tree
    is reported by the prohibited-cache scan, not by a phantom "missing
    RECORD file" integrity error.

    Returns the number of RECORD lines dropped."""
    dropped = 0
    site = runtime_dir / "Lib" / "site-packages"
    if not site.is_dir():
        return dropped
    for dist_dir in sorted(
        p for p in site.iterdir() if p.is_dir() and p.name.endswith(".dist-info")
    ):
        record = dist_dir / "RECORD"
        if not record.is_file():
            continue
        kept: list[str] = []
        removed_here = 0
        for ln in record.read_text(encoding="utf-8").splitlines():
            if not ln:
                continue
            path = _record_entry_path(ln)
            parts = path.split("/")
            if (
                path.endswith(".pyc")
                or "__pycache__" in parts
                or path.startswith("../../Scripts/")
            ):
                removed_here += 1
                continue
            kept.append(ln)
        if removed_here:
            dropped += removed_here
            record.write_text("\n".join(kept) + "\n", encoding="utf-8", newline="\n")
    return dropped


def normalized_record_sha256(record_path: Path) -> str:
    """Deterministic SHA-256 over the installed RECORD (consistency record).

    pip regenerates RECORD at install time and appends entries for the
    console-script launchers it generates (``../../Scripts/*.exe``); those
    entries are dropped from the on-disk RECORD by
    ``drop_noncanonical_record_lines`` because the launcher binaries are not
    shipped (see the launcher contract). ``direct_url.json`` entries (which
    point at the build machine's artifact cache) are removed from the tree
    together with their RECORD line. The exact reviewed scipy 1.18.1
    self-copy entry (``SCIPY_SELF_COPY``) is a documented upstream defect
    artifact.

    This digest is a CONSISTENCY record (manifest Class B). The
    AUTHORITATIVE tree binding is the installed-tree digest over actual
    file bytes that anchors the runtime ID (see
    ``compute_installed_tree_digest``); the on-disk RECORD only becomes
    authoritative for per-file byte checks AFTER the runtime ID (and with
    it the tree digest) is verified against the current Commit-1 inputs.
    Excluding non-canonical entries here does not weaken verification:
    every tampered file is detected by the tree-digest/ID anchor and by
    ``verify_record_integrity`` over the actual bytes."""
    if not record_path.is_file():
        return ""
    lines: list[str] = []
    for raw in record_path.read_text(encoding="utf-8").splitlines():
        if not raw:
            continue
        path = _record_entry_path(raw)
        if path.startswith("../../Scripts/"):
            continue
        if path == SCIPY_SELF_COPY["filename"]:
            continue
        if path == "direct_url.json" or path.endswith(".dist-info/direct_url.json"):
            continue
        lines.append(raw)
    lines.sort()
    if not lines:
        return ""
    return locklib.sha256_bytes("\n".join(lines).encode("utf-8"))


def _parse_record_lines(record_path: Path) -> list[tuple[str, str, str]]:
    """(path, hash-field, size-field) per RECORD line; hash '' if absent."""
    entries: list[tuple[str, str, str]] = []
    for raw in record_path.read_text(encoding="utf-8").splitlines():
        if not raw:
            continue
        parts = raw.split(",")
        path = _record_entry_path(raw)
        digest = parts[1] if len(parts) > 1 else ""
        size = parts[2] if len(parts) > 2 else ""
        entries.append((path, digest, size))
    return entries


def verify_record_integrity(
    runtime_dir: Path, site_packages: Path, dist_dirs: list[Path]
) -> list[str]:
    """Byte-level payload integrity per RECORD semantics.

    ``dist_dirs`` is the verification scope: in ``verify_runtime`` it is
    EVERY distribution directory physically present in the tree
    (filesystem-derived; the manifest cannot shrink it). For each
    distribution: package Python source and data files, native ``.dll`` and
    ``.pyd`` payloads, package executables, critical package metadata
    (METADATA etc.), and the zero-byte scipy self-copy artifact. (The pip
    console launcher ``.exe`` binaries are not shipped - see the launcher
    contract - so their RECORD lines are absent after the build-time
    normalization.)

    The on-disk RECORD is trusted for these per-file byte checks ONLY after
    the runtime ID (which binds the installed-tree digest over the actual
    file bytes) has been verified against the current Commit-1 inputs: any
    consistent edit of a payload file and its RECORD entry changes the
    recomputed tree digest and fails the runtime-ID check, so the RECORD
    cannot be used to hide a payload edit.

    Bundled (interpreter-baseline) distributions may carry RECORD entries
    that the builder re-anchored at build time from the captured
    pre-install baseline authority (``reconcile_baseline_records``,
    reviewed exception set only: the pinned install_only_stripped archive
    normalizes the vendored distlib executables, so the upstream wheel-era
    digests are stale while the captured archive bytes are the authority).
    Baseline files are verified byte-exact against the pre-install
    capture at build time, so post-install mutation can never be
    normalized away. Non-baseline distributions are never re-anchored.

    Every RECORD entry is resolved inside the runtime root and checked:
    the file must exist; when RECORD carries a ``sha256=<b64>`` hash the
    file bytes must hash to it; a non-empty size field must match. The
    RECORD's own entry (empty hash) is checked for existence only.

    Returns violation strings; empty means the payload is intact."""
    violations: list[str] = []
    for dist_dir in dist_dirs:
        record = dist_dir / "RECORD"
        if not record.is_file():
            violations.append(f"{dist_dir.name}: RECORD missing")
            continue
        for path, digest, size in _parse_record_lines(record):
            if path.endswith("/RECORD") or path == "RECORD":
                continue  # RECORD's own entry: existence only, hash is ''
            target = (site_packages / path).resolve()
            if not (target == runtime_dir or runtime_dir in target.parents):
                violations.append(f"{dist_dir.name}: RECORD entry escapes runtime: {path}")
                continue
            if not target.is_file():
                violations.append(f"{dist_dir.name}: missing RECORD file: {path}")
                continue
            if digest.startswith("sha256="):
                expected = digest[len("sha256=") :]
                padded = expected + "=" * (-len(expected) % 4)
                try:
                    expected_digest = base64.urlsafe_b64decode(padded.encode("ascii"))
                except (ValueError, TypeError):
                    violations.append(f"{dist_dir.name}: malformed RECORD hash: {path}")
                    continue
                if hashlib.sha256(target.read_bytes()).digest() != expected_digest:
                    violations.append(f"{dist_dir.name}: RECORD hash mismatch: {path}")
                    continue
            if size:
                try:
                    if target.stat().st_size != int(size):
                        violations.append(f"{dist_dir.name}: RECORD size mismatch: {path}")
                except ValueError:
                    violations.append(f"{dist_dir.name}: malformed RECORD size: {path}")
    return violations


def capture_baseline_authority(
    runtime_dir: Path,
    baseline_dist_dirs: dict[str, str],
) -> dict[str, dict]:
    """Capture the authoritative baseline RECORD state.

    MUST be called immediately after the pinned Python archive has been
    SHA-256 verified, safely extracted, and license-checked, and BEFORE
    wheel installation or any other step that can mutate the tree. The
    captured data is therefore the verified archive's state: it is NEVER
    recomputed from the (possibly installer-mutated) post-install staging
    tree.

    For each baseline distribution, captures:

      * ``paths``: the EXACT normalized set of RECORD entry paths as
        shipped by the verified archive (the authoritative pre-install
        RECORD path membership, including the RECORD's own entry);
      * ``files``: for every path that references an existing file,
        (SHA-256, size) of the freshly extracted (archive) bytes.

    This captured state is the sole authority for baseline RECORD
    reconciliation (``reconcile_baseline_records``): the post-install
    RECORD's path membership must be exactly ``paths`` minus the
    explicitly approved droppable paths, and every referenced file must
    still be byte-identical to the captured archive bytes - so neither a
    RECORD line deletion, a RECORD line addition, nor a file/RECORD
    co-edit can be normalized away.

    The inventory holds relative paths, digests and sizes only: no
    absolute paths, no extraction root, no timestamps, no host data. It
    is build-time-only validation state and does NOT participate in the
    runtime ID (the installed-tree digest over actual bytes already covers
    every tree byte, so no identity input needs to change)."""
    authority: dict[str, dict] = {}
    site = runtime_dir / "Lib" / "site-packages"
    for name, dist_dir_str in sorted(baseline_dist_dirs.items()):
        record = Path(dist_dir_str) / "RECORD"
        paths: set[str] = set()
        files: dict[str, tuple[str, int]] = {}
        if record.is_file():
            for path, _digest, _size in _parse_record_lines(record):
                paths.add(path)
                target = site / path
                if not target.is_file():
                    continue
                data = target.read_bytes()
                files[path] = (hashlib.sha256(data).hexdigest(), len(data))
        authority[name] = {"paths": frozenset(paths), "files": files}
    return authority


def _approved_droppable_baseline_paths(path: str) -> bool:
    """EXPLICIT, closed permission set for baseline RECORD paths that
    approved Phase-13 normalizations deliberately remove (line dropped
    from the RECORD, file removed from the tree). Only these three
    reviewed normalizations exist - no generic pattern beyond them:

      * direct_url provenance pointers
        (``direct_url.json`` / ``*.dist-info/direct_url.json``) -
        removed by the direct-url normalization;
      * generated bytecode entries (``*.pyc`` / ``__pycache__``) - the
        files are scrubbed and their RECORD lines dropped by the
        bytecode-records normalization;
      * pip console launcher entries (``../../Scripts/*``) - the launcher
        binaries are removed by the pip-launchers normalization (entry
        points recorded in the manifest instead).

    Every other baseline RECORD path is NON-DROPPABLE: it must remain in
    the post-install RECORD exactly as captured pre-install."""
    if path == "direct_url.json" or path.endswith(".dist-info/direct_url.json"):
        return True
    if path.endswith(".pyc") or "__pycache__" in path.split("/"):
        return True
    if path.startswith("../../Scripts/"):
        return True
    return False


def reconcile_baseline_records(
    runtime_dir: Path,
    baseline_authority: dict[str, dict],
    baseline_dist_dirs: dict[str, str],
) -> tuple[dict[str, list[str]], list[str]]:
    """Reconcile the on-disk RECORDs of BUNDLED (interpreter-baseline)
    distributions against the CAPTURED pre-install baseline authority.

    Enforced per baseline distribution, in this order (all fail closed):

      A. EXACT PATH MEMBERSHIP: the post-install RECORD's normalized
         path set must equal the captured pre-install path set MINUS the
         explicitly approved droppable paths
         (``_approved_droppable_baseline_paths``). Violations: a
         missing non-droppable path (RECORD-line deletion, whether or
         not the file was touched), an unexpected added path (including
         a leftover droppable line that the normalizations dropped), a
         duplicate normalized path, or a path case/alias collision;
      B. FILE AUTHORITY: every path referenced by the post-install
         RECORD (outside the approved droppable set) must be byte-
         identical to the captured pre-install (verified-archive) bytes
         with the captured size - a captured path without a pre-install
         file that now exists is likewise rejected;
      C. ONLY the reviewed exception set
         (``BASELINE_RECORD_REANCHOR_EXCEPTIONS``: the pinned archive's
         bundled pip distlib executable normalization) may have its
         stale hash/size FIELDS rewritten, and only to the CAPTURED
         authority values, and only when the file's bytes are exactly
         the captured bytes; the path is never altered and no line is
         ever dropped;
      D. every other stale hash/size entry is a violation.

    Stages A and B run BEFORE any re-anchoring: the allowlist can never
    mask a path deletion/addition or a file modification. A baseline
    RECORD that existed pre-install must still exist.

    Non-baseline distributions are never touched by this step. The
    caller must fail the build (before promotion) on ANY violation: a
    baseline RECORD may never be used to launder post-install
    modifications, and the installed-tree digest / runtime ID computed
    afterwards bind exactly the verified-archive bytes.

    Returns ``(reanchored, violations)``: ``reanchored`` maps distribution
    name to the allowlisted entry paths rewritten (record it as a manifest
    normalization entry); ``violations`` is a list of fail-closed reasons
    (empty when reconciliation is clean)."""
    reanchored: dict[str, list[str]] = {}
    violations: list[str] = []
    site = runtime_dir / "Lib" / "site-packages"

    def _path_field(raw: str, path: str) -> str | None:
        """The exact path field of a raw RECORD line (pip quotes paths
        containing special characters); None when it cannot be rewritten
        safely (embedded quotes) - such lines are then left untouched."""
        if raw.startswith('"'):
            close = raw.find('"', 1)
            if close == -1 or '"' in raw[1:close]:
                return None
            return raw[: close + 1]
        return raw.split(",")[0] if raw else path

    def _record_b64(hex_digest: str) -> str:
        return "sha256=" + base64.urlsafe_b64encode(
            bytes.fromhex(hex_digest)
        ).decode("ascii").rstrip("=")

    for name, dist_dir_str in sorted(baseline_dist_dirs.items()):
        meta = baseline_authority.get(name, {"paths": frozenset(), "files": {}})
        captured_paths: frozenset[str] = meta["paths"]
        authority_files: dict[str, tuple[str, int]] = meta["files"]
        exceptions = BASELINE_RECORD_REANCHOR_EXCEPTIONS.get(name, frozenset())
        dist_dir = Path(dist_dir_str)
        record = dist_dir / "RECORD"
        if not record.is_file():
            if captured_paths:
                violations.append(f"{name}: baseline RECORD missing (pre-install RECORD present)")
            continue
        raw_lines = [ln for ln in record.read_text(encoding="utf-8").splitlines() if ln]
        entries = _parse_record_lines(record)
        post_paths = [path for path, _digest, _size in entries]
        post_set = set(post_paths)

        # -- A. EXACT path membership (before any hash/size processing):
        #    post-install set == captured set minus the approved
        #    droppable paths; duplicates and case/alias collisions are
        #    rejected on both sides.
        droppable = {p for p in captured_paths if _approved_droppable_baseline_paths(p)}
        expected_paths = captured_paths - droppable
        missing_paths = sorted(expected_paths - post_set)
        unexpected_paths = sorted(post_set - expected_paths)
        seen: set[str] = set()
        duplicates = sorted({p for p in post_paths if p in seen or seen.add(p)})
        casefolded: dict[str, list[str]] = {}
        for p in sorted(post_set):
            casefolded.setdefault(p.casefold(), []).append(p)
        case_collisions = sorted(
            {p for group in casefolded.values() if len(group) > 1 for p in group}
        )
        member_violations: list[str] = []
        for p in missing_paths:
            member_violations.append(f"{name}: baseline RECORD path deleted: {p}")
        for p in unexpected_paths:
            member_violations.append(f"{name}: baseline RECORD path added (not in pre-install authority): {p}")
        for p in duplicates:
            member_violations.append(f"{name}: duplicate baseline RECORD path: {p}")
        for p in case_collisions:
            member_violations.append(f"{name}: baseline RECORD path case collision: {p}")
        if member_violations:
            violations.extend(member_violations)
            continue  # membership is broken: no file checks, no re-anchor

        # -- B. File authority: every remaining referenced path must be
        #    the captured archive's bytes (size included).
        file_violations: list[str] = []
        for path, _digest, _size in entries:
            if path.endswith("/RECORD") or path == "RECORD":
                target = site / path
                if not target.is_file():
                    file_violations.append(f"{name}: baseline RECORD file missing: {path}")
                continue
            if _approved_droppable_baseline_paths(path):
                continue  # approved removals: line dropped, file removed
            expected = authority_files.get(path)
            if expected is None:
                file_violations.append(f"{name}: baseline file not present pre-install: {path}")
                continue
            expected_digest_hex, expected_size = expected
            target = site / path
            if not target.is_file():
                file_violations.append(f"{name}: baseline file missing: {path}")
                continue
            actual = target.read_bytes()
            if (
                hashlib.sha256(actual).hexdigest() != expected_digest_hex
                or len(actual) != expected_size
            ):
                # Post-install modification of a baseline file: NEVER
                # normalized, regardless of the RECORD's contents.
                file_violations.append(f"{name}: baseline file modified since capture: {path}")
        if file_violations:
            violations.extend(file_violations)
            continue  # files are not the captured bytes: no re-anchor

        # -- C/D. Only now (membership exact, files exactly the captured
        #    archive bytes) may the reviewed exception set re-anchor its
        #    stale hash/size fields to the CAPTURED values; every other
        #    stale entry fails closed.
        new_lines: list[str] = []
        touched: list[str] = []
        for index, (path, digest, size) in enumerate(entries):
            raw = raw_lines[index] if index < len(raw_lines) else ""
            if path.endswith("/RECORD") or path == "RECORD":
                new_lines.append(raw or path)
                continue
            if _approved_droppable_baseline_paths(path):
                new_lines.append(raw or path)
                continue
            expected_digest_hex, expected_size = authority_files[path]
            # The file is exactly the captured bytes (stage B), so the
            # expected on-disk hash/size fields are the captured values.
            actual_digest = "sha256=" + base64.urlsafe_b64encode(
                bytes.fromhex(expected_digest_hex)
            ).decode("ascii").rstrip("=")
            if digest == actual_digest and size in ("", str(expected_size)):
                new_lines.append(raw or path)
                continue
            if path not in exceptions:
                violations.append(f"{name}: stale baseline RECORD entry outside the reviewed exception set: {path}")
                new_lines.append(raw or path)
                continue
            path_field = _path_field(raw, path)
            if path_field is None:
                # Cannot rewrite safely: leave untouched, so the stale
                # entry fails the post-promotion RECORD check (fail
                # closed).
                violations.append(f"{name}: stale allowlisted RECORD entry could not be rewritten safely: {path}")
                new_lines.append(raw)
                continue
            if digest == "":
                # No-hash entry: keep the no-hash semantics, rewrite only
                # the (stale) size field to the captured size.
                new_lines.append(",".join([path_field, "", str(expected_size)]))
            else:
                new_lines.append(",".join([path_field, _record_b64(expected_digest_hex), str(expected_size)]))
            touched.append(path)
        if touched:
            record.write_text("\n".join(new_lines) + "\n", encoding="utf-8", newline="\n")
            reanchored[name] = sorted(touched)
    return reanchored, violations


def _metadata_name_version(metadata: Path) -> tuple[str, str]:
    """Parse the first ``Name:`` / ``Version:`` headers of a dist METADATA
    file; ('', '') when unreadable or absent."""
    name = ""
    version = ""
    try:
        for line in metadata.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith("Name:"):
                if not name:
                    name = line.split(":", 1)[1].strip()
            elif line.startswith("Version:"):
                if not version:
                    version = line.split(":", 1)[1].strip()
    except OSError:
        pass
    return name, version


def enumerate_tree_distributions(
    runtime_dir: Path,
) -> tuple[dict[str, list[tuple[str, Path]]], list[str]]:
    """Enumerate installed distributions DIRECTLY from the tree.

    Returns ``(dist_map, duplicates)``:

    * ``dist_map``: normalized project name -> list of ``(version,
      dist_info_dir)`` for every ``*.dist-info`` / ``*.egg-info`` directory
      physically present under ``Lib/site-packages`` (METADATA Name/Version
      when available, directory-name fallback otherwise);
    * ``duplicates``: sorted normalized names present in MORE THAN ONE
      directory (same or different version).

    This enumeration is independent of the manifest: the manifest's
    ``installed_tree`` inventory is a consistency record and can NEVER
    define which distributions exist or which ones are integrity-checked.
    Duplicate distributions are an integrity violation in themselves (two
    inventories could claim the same package name and shadow each
    other's files / RECORD entries), so the caller rejects them."""
    site = runtime_dir / "Lib" / "site-packages"
    dist_map: dict[str, list[tuple[str, Path]]] = {}
    if site.is_dir():
        for dist_dir in sorted(site.iterdir()):
            if not dist_dir.is_dir():
                continue
            if not (
                dist_dir.name.endswith(".dist-info")
                or dist_dir.name.endswith(".egg-info")
            ):
                continue
            name, version = "", ""
            metadata = dist_dir / "METADATA"
            if metadata.is_file():
                name, version = _metadata_name_version(metadata)
            if not name:
                stem = dist_dir.name.removesuffix(".dist-info").removesuffix(".egg-info")
                if "-" in stem:
                    name, version = stem.rsplit("-", 1)
                elif "_" in stem:
                    name, version = stem.rsplit("_", 1)
                else:
                    name = stem
            dist_map.setdefault(locklib.normalized_name(name), []).append((version, dist_dir))
    duplicates = sorted(n for n, entries in dist_map.items() if len(entries) > 1)
    return dist_map, duplicates


def compute_installed_tree_digest(runtime_dir: Path) -> str:
    """Canonical integrity digest over the ACTUAL bytes of every file in the
    (normalized) runtime tree.

    The map is {relative POSIX path: file SHA-256} over every regular file
    under ``runtime_dir`` EXCEPT the manifest itself (it is written after the
    tree is finalized and carries non-canonical operational fields). At
    build time this runs on the fully normalized staging tree (generated
    bytecode scrubbed, launcher .exe binaries removed, RECORD lines kept
    self-consistent), so for identical inputs the digest is reproducible
    and may anchor the runtime ID. At verification time the same function
    runs on the promoted tree; any post-build modification of any file
    (payload, RECORD, METADATA, planted or deleted files, tree structure)
    changes the digest and therefore the expected runtime ID.

    The digest hashes actual file bytes directly - it never reads the
    RECORD's claimed hashes - so editing a RECORD cannot hide a payload
    edit.
    """
    entries: dict[str, str] = {}
    for path in sorted(runtime_dir.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(runtime_dir).as_posix()
        if rel == MANIFEST_NAME:
            continue
        entries[rel] = locklib.sha256_file_raw(path)
    return locklib.sha256_bytes(
        locklib.canonical_json(entries).encode("ascii")
    )


def build_installed_tree_inventory(
    runtime_dir: Path,
    locked_names: dict[str, str],
    dist_info_map: dict[str, str],
) -> dict:
    root_files = {}
    for path in sorted(runtime_dir.iterdir()):
        if path.is_file():
            root_files[path.name] = locklib.sha256_file_raw(path)
    distributions: dict[str, dict[str, str]] = {}
    for name in sorted(locked_names):
        raw_loc = dist_info_map.get(name, "")
        dist_dir = None
        if raw_loc:
            candidate = (runtime_dir / raw_loc.lstrip("/")).resolve()
            try:
                candidate.relative_to(runtime_dir)
            except ValueError:
                candidate = None
            if candidate is not None and candidate.is_dir():
                dist_dir = candidate
        if dist_dir is None:
            suffix = f"{name.replace('-', '_')}-{locked_names[name]}"
            for candidate in sorted((runtime_dir / "Lib" / "site-packages").glob(f"*{suffix}.dist-info")):
                if candidate.is_dir():
                    dist_dir = candidate
                    break
        if dist_dir is None:
            dist_dir = next(
                (
                    c
                    for c in sorted((runtime_dir / "Lib" / "site-packages").iterdir())
                    if c.is_dir() and c.name.endswith(".dist-info")
                    and locklib.normalized_name(c.name.split("-")[0]) == name
                ),
                None,
            )
        if dist_dir is None:
            raise BuilderError("installed-tree", f"dist-info not found for {name}")
        metadata = dist_dir / "METADATA"
        record = dist_dir / "RECORD"
        if not metadata.is_file():
            raise BuilderError("installed-tree", f"METADATA missing for {name}")
        distributions[name] = {
            "dist_info": dist_dir.relative_to(runtime_dir).as_posix(),
            "metadata_sha256": locklib.sha256_file_raw(metadata),
            "record_sha256": normalized_record_sha256(record),
        }
    inventory = {
        "distributions": distributions,
        "root_files": root_files,
    }
    # The authoritative tree binding (anchors the runtime ID); the
    # per-distribution digests above are consistency records.
    inventory["inventory_sha256"] = compute_installed_tree_digest(runtime_dir)
    return inventory


