def _synthetic_batch(model, batch=None, identical=False):
    n = model.get_batch_size() if batch is None else batch
    if model.model_data_format == "NHWC":
        image_shape, mask_shape = (n, 96, 96, 3), (n, 96, 96, 1)
    else:
        image_shape, mask_shape = (n, 3, 96, 96), (n, 1, 96, 96)
    rng = np.random.default_rng(1400)
    if identical:
        image = rng.random(image_shape[1:], dtype=np.float32)
        mask = rng.random(mask_shape[1:], dtype=np.float32)
        images = [np.repeat(image[None], n, axis=0) for _ in range(4)]
        masks = [np.repeat(mask[None], n, axis=0) for _ in range(2)]
    else:
        images = [rng.random(image_shape, dtype=np.float32) for _ in range(4)]
        masks = [rng.random(mask_shape, dtype=np.float32) for _ in range(2)]
    return (images[0], images[1], masks[0],
            images[2], images[3], masks[1])


def _controlled_dropout(shape, p, dtype, device=None, *, counter):
    index = counter[0]
    counter[0] += 1
    size = int(np.prod(tuple(shape), dtype=np.int64))
    phase = _stable_number(f"mask-{index}") % 10
    values = (((np.arange(size) + phase) % 10) < 3).astype(np.float32)
    return torch.from_numpy(values.reshape(tuple(shape))).to(
        device=device, dtype=dtype)


def test_official_source_authentication_rejects_wrong_commit_and_dirty_tree(
        plain_tmp):
    root = Path(plain_tmp) / "official_auth"
    root.mkdir()

    def git(*args):
        return subprocess.run(
            ["git", "-C", str(root), *args], check=True,
            text=True, encoding="utf-8", stdout=subprocess.PIPE,
            stderr=subprocess.PIPE).stdout.strip()

    git("init", "-q")
    git("config", "user.name", "Quick96 Test")
    git("config", "user.email", "quick96-test@example.invalid")
    marker = root / "oracle.py"
    marker.write_text("official = True\n", encoding="utf-8")
    git("add", "oracle.py")
    git("commit", "-q", "--no-gpg-sign", "-m", "oracle source")
    local_commit = git("rev-parse", "HEAD")

    with pytest.raises(OfficialSourceAuthenticationError,
                       match="official source HEAD mismatch"):
        authenticate_official_root(root)

    authenticated = authenticate_official_root(
        root, expected_commit=local_commit)
    assert authenticated["commit"] == local_commit
    assert authenticated["tracked_state"] == "clean"

    marker.write_text("official = False\n", encoding="utf-8")
    with pytest.raises(OfficialSourceAuthenticationError,
                       match="tracked modifications"):
        authenticate_official_root(root, expected_commit=local_commit)


