    before_probes = _official_probes(encoder, before, trainable[:4])
    after_probes = _official_probes(encoder, after, trainable[:4])
    accumulator_probes = _official_probes(
        optimizer, accumulators, accumulators)
    for actual, key in (
            (before_probes, "parameter_before_probes"),
            (after_probes, "parameter_after_probes"),
            (accumulator_probes, "accumulator_probes")):
        expected = fixture[key]
        assert actual.shape == (4, 3)
