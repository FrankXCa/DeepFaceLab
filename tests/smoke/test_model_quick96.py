# Frozen FP32 cross-framework contract. These are absolute tolerances because
# every fixture field has a fixed bounded synthetic scale. They leave useful
# headroom for different FP32 convolution/reduction accumulation orders while
# remaining tight enough to reject layout, activation, masking, or reduction
# changes: encoder has four strided convolutions; inter is a small-valued
# dense/upscale result; decoder and blur outputs are bounded near [0, 1]; the
# two loss vectors include large spatial reductions. Controlled RMSprop is a
# scalar elementwise contract and is required to remain exact below.
PARITY_FIELDS = {
    "encoder_src": ((2, 18432), np.float32, 3e-5),
    "inter_src": ((2, 6, 6, 128), np.float32, 2e-7),
    "decoder_src_face": ((2, 96, 96, 3), np.float32, 2e-6),
    "decoder_src_mask": ((2, 96, 96, 1), np.float32, 2e-6),
    "decoder_dst_face": ((2, 96, 96, 3), np.float32, 2e-6),
    "decoder_dst_mask": ((2, 96, 96, 1), np.float32, 2e-6),
    "ae_view_src": ((2, 96, 96, 3), np.float32, 2e-6),
    "ae_view_dst": ((2, 96, 96, 3), np.float32, 2e-6),
    "ae_view_dst_mask": ((2, 96, 96, 1), np.float32, 2e-6),
    "ae_view_swap": ((2, 96, 96, 3), np.float32, 2e-6),
    "ae_view_swap_mask": ((2, 96, 96, 1), np.float32, 2e-6),
    "ae_merge_face": ((2, 96, 96, 3), np.float32, 2e-6),
    "ae_merge_src_mask": ((2, 96, 96, 1), np.float32, 2e-6),
    "ae_merge_dst_mask": ((2, 96, 96, 1), np.float32, 2e-6),
    "src_mask_blur": ((2, 96, 96, 1), np.float32, 1e-6),
    "dst_mask_blur": ((2, 96, 96, 1), np.float32, 1e-6),
    "src_loss": ((2,), np.float32, 2e-5),
    "dst_loss": ((2,), np.float32, 1e-5),
}


def _assert_parity_field(name, actual, expected):
    shape, dtype, atol = PARITY_FIELDS[name]
    actual = np.asarray(actual)
    expected = np.asarray(expected)
    assert actual.shape == shape
    assert expected.shape == shape
    assert actual.dtype == dtype
    assert expected.dtype == dtype
    np.testing.assert_allclose(actual, expected, rtol=0.0, atol=atol,
                               err_msg=name)


def _reference():
    fixture = np.load(REFERENCE)
    return fixture, json.loads(str(fixture["metadata"]))


def _components(device_config=None):
    nn.initialize(device_config or nn.DeviceConfig.CPU(), data_format="NHWC")
    archi = nn.DeepFakeArchi(96, opts="ud")
    encoder = archi.Encoder(3, 64, name="encoder")
    encoder_out_ch = encoder.get_out_ch() * encoder.get_out_res(96) ** 2
    inter = archi.Inter(encoder_out_ch, 128, 128, name="inter")
    decoder_src = archi.Decoder(inter.get_out_ch(), 64, 16,
                                name="decoder_src")
    decoder_dst = archi.Decoder(inter.get_out_ch(), 64, 16,
                                name="decoder_dst")
    return encoder, inter, decoder_src, decoder_dst


def _load_synthetic_components(components, metadata, root):
    root = Path(root)
    for component in components:
        payload = {}
        for item in metadata["components"][component.name]:
            full_name = f"{component.name}/{item['key']}"
            payload[item["key"]] = synthetic_value(
                full_name, tuple(item["shape"]))
        path = root / f"{component.name}.npy"
        path.write_bytes(pickle.dumps(payload, 4))
        assert component.load_weights(path)


def _np(tensor):
    return tensor.detach().cpu().numpy()


def _tensor_digest(tensor):
    value = tensor.detach().cpu().contiguous().numpy()
    return hashlib.sha256(value.tobytes()).hexdigest()


def _probes(values):
    result = []
    for value in values:
        flat = _np(value).reshape(-1)
        indexes = sorted({0, len(flat) // 2, len(flat) - 1})
        result.append([float(flat[i]) for i in indexes])
    return np.asarray(result, dtype=np.float64)


def _official_probes(saveable, values, identities):
    converted = [
        saveable.convert_weight_to_official(_np(value), identity)
        for value, identity in zip(values, identities)]
    result = []
    for value in converted:
        flat = np.asarray(value).reshape(-1)
        indexes = sorted({0, len(flat) // 2, len(flat) - 1})
        result.append([float(flat[i]) for i in indexes])
    return np.asarray(result, dtype=np.float64)


