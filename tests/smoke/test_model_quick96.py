    for name, actual in comparisons.items():
        _assert_parity_field(name, _np(actual), fixture[name])

    srcm_blur = nn.gaussian_blur(target_srcm, 3)
    dstm_blur = nn.gaussian_blur(target_dstm, 3)
    _assert_parity_field("src_mask_blur", _np(srcm_blur),
                         fixture["src_mask_blur"])
    _assert_parity_field("dst_mask_blur", _np(dstm_blur),
                         fixture["dst_mask_blur"])
    assert not torch.equal(srcm_blur, target_srcm)
    assert not torch.equal(dstm_blur, target_dstm)

    shell = Quick96Model.__new__(Quick96Model)
    shell.resolution = 96
    targets = {
        "target_src": target_src, "target_dst": target_dst,
        "target_srcm": target_srcm, "target_dstm": target_dstm,
        "target_srcm_blur": srcm_blur, "target_dstm_blur": dstm_blur,
    }
    predictions = {
        "pred_src_src": src_face, "pred_src_srcm": src_mask,
        "pred_dst_dst": dst_face, "pred_dst_dstm": dst_mask,
    }
    src_loss, dst_loss = shell._loss_vectors(targets, predictions)
    src_target_masked = target_src * srcm_blur
    src_pred_masked = src_face * srcm_blur
    src_dssim = torch.mean(
        10 * nn.dssim(src_target_masked, src_pred_masked,
                      max_val=1.0, filter_size=int(96 / 11.6)), dim=1)
    src_pixel_mse = torch.mean(
        10 * torch.square(src_target_masked - src_pred_masked),
        dim=(1, 2, 3))
