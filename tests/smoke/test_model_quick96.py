def test_lr_dropout_fresh_masks_probability_dtype_and_device(monkeypatch):
    nn.initialize(nn.DeviceConfig.CPU(), data_format="NHWC")
    parameter = torch.nn.Parameter(torch.zeros(200_000, dtype=torch.float32))
    parameter._dfl_name = "encoder/test:0"
    optimizer = nn.RMSprop(lr=1.0, rho=0.9, lr_dropout=0.3,
                           name="src_dst_opt")
    optimizer.initialize_variables([parameter], vars_on_cpu=True)
    seen = []
    real = nn.random_binomial

    def observed(shape, p, dtype, device=None):
        mask = real(shape, p=p, dtype=dtype, device=device)
        seen.append(mask.detach().clone())
        return mask

    monkeypatch.setattr(nn, "random_binomial", observed)
    for _ in range(2):
        optimizer.get_update_op([(torch.ones_like(parameter), parameter)])()
    assert len(seen) == 2
    assert seen[0].dtype == parameter.dtype
    assert seen[0].device == parameter.device
    assert not torch.equal(seen[0], seen[1])
    for mask in seen:
        assert abs(float(mask.mean()) - 0.3) < 0.01


def test_lr_dropout_independent_parameter_masks_in_same_step(monkeypatch):
    nn.initialize(nn.DeviceConfig.CPU(), data_format="NHWC")
    parameters = [
        torch.nn.Parameter(torch.zeros(10_000, dtype=torch.float32))
        for _ in range(2)]
    for index, parameter in enumerate(parameters):
        parameter._dfl_name = f"encoder/test_{index}:0"
    optimizer = nn.RMSprop(lr=1.0, rho=0.9, lr_dropout=0.3,
                           name="src_dst_opt")
    optimizer.initialize_variables(parameters, vars_on_cpu=True)
    calls = []

    def instrumented(shape, p, dtype, device=None):
        call_index = len(calls)
        size = int(np.prod(tuple(shape), dtype=np.int64))
        values = (((np.arange(size) + call_index) % 10) < 3).astype(
            np.float32)
        mask = torch.from_numpy(values.reshape(tuple(shape))).to(
            device=device, dtype=dtype)
        calls.append({"mask": mask, "p": p, "dtype": dtype,
                      "device": device})
        return mask

    monkeypatch.setattr(nn, "random_binomial", instrumented)
    optimizer.get_update_op([
        (torch.ones_like(parameter), parameter)
        for parameter in parameters])()

    # Both calls occurred inside the one optimizer step (one iteration), and
    # the deterministic phases prove two samples rather than one shared mask.
    assert int(optimizer.iterations) == 1
    assert len(calls) == 2
    first, second = calls
    for call, parameter in zip(calls, parameters):
        assert call["p"] == 0.3
        assert call["dtype"] == parameter.dtype
        assert call["device"] == parameter.device
        assert call["mask"].dtype == parameter.dtype
        assert call["mask"].device == parameter.device
        assert float(call["mask"].mean()) == pytest.approx(0.3, abs=1e-7)
    assert first["mask"] is not second["mask"]
    assert (first["mask"].untyped_storage().data_ptr()
            != second["mask"].untyped_storage().data_ptr())
    assert not torch.equal(first["mask"], second["mask"])


