def test_simulated_two_replica_batch_sum_mean_one_step_and_sync(plain_tmp,
                                                                monkeypatch):
    assert [Quick96Model._official_batch_layout(n) for n in range(6)] == [
        (1, 4, 4), (1, 4, 4), (2, 2, 4), (3, 1, 3),
        (4, 1, 4), (5, 1, 5)]
    model = _make_model(Path(plain_tmp) / "simulated")
    try:
        batch = _synthetic_batch(model, identical=True)
        captured = []
        real_get_update_op = model.src_dst_opt.get_update_op
        monkeypatch.setattr(
            model.src_dst_opt, "get_update_op",
            lambda gv: (lambda: captured.append(
                [gradient.detach().clone() for gradient, _ in gv])))
        model._src_dst_train_vectors(*batch)
        single = captured.pop()

        model.replica_plan.dispose()
        model.replica_plan = nn.ReplicaPlan.from_torch_devices(
            torch.device("cpu"), [torch.device("cpu"), torch.device("cpu")])
        model._quick96_tower_offset = 0
        model.tower_devices = model.replica_plan.replica_devices
        model._quick96_bs_per_tower = 2
        for component in model._quick96_components:
            model.replica_plan.add_component(component)
        model.replica_plan.initial_sync()

        shard_sizes = []
        real_forward = model._forward_tower

        def observed_forward(warped_src, warped_dst, tower,
                             include_swap=True):
            shard_sizes.append(len(warped_src))
            return real_forward(warped_src, warped_dst, tower, include_swap)

        monkeypatch.setattr(model, "_forward_tower", observed_forward)
        model._src_dst_train_vectors(*batch)
        multi = captured.pop()
        assert shard_sizes == [2, 2]
        for one, many in zip(single, multi):
            # CPU convolution kernels may accumulate a batch-of-four and two
            # batches-of-two in a slightly different order. Compare stable
            # whole-gradient norms: the factor-of-two relationship (single
            # batch sum versus the mean of two equal shard sums) is the
            # contract under test and sharply distinguishes a missing mean.
            one_norm = torch.linalg.vector_norm(one.double())
            multi_norm = torch.linalg.vector_norm((many * 2).double())
            torch.testing.assert_close(one_norm, multi_norm,
                                       rtol=2e-3, atol=2e-5)

        monkeypatch.setattr(model.src_dst_opt, "get_update_op",
                            real_get_update_op)
        counter = [0]
        monkeypatch.setattr(
            nn, "random_binomial",
            lambda shape, p, dtype, device=None: _controlled_dropout(
                shape, p, dtype, device, counter=counter))
        src_display, dst_display = model._src_dst_train_vectors(*batch)
        assert tuple(src_display.shape) == (2,)
        assert tuple(dst_display.shape) == (2,)
        assert int(model.src_dst_opt.iterations) == 1
        for component_set in model.replica_plan.components:
            for canonical, mirror in zip(component_set.canonical_params,
                                         component_set.mirror_params[1]):
                assert torch.equal(canonical, mirror)
        assert [filename for _, filename in model.get_model_filename_list()] == [
            "encoder.npy", "inter.npy", "decoder_src.npy",
            "decoder_dst.npy", "src_dst_opt.npy"]
    finally:
        model.finalize()


