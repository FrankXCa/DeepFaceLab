def test_cpu_training_iteration_reuse_save_resume_and_strict_failure(plain_tmp,
                                                                     monkeypatch):
    root = Path(plain_tmp) / "quick96_cpu"
    model = _make_model(root)
    try:
        assert model.get_batch_size() == 4
        assert model.models_opt_on_gpu is False
        assert model.low_vram_split is False
        assert {p.device.type for p in model.src_dst_trainable_weights} == {"cpu"}
        assert len(model.src_dst_trainable_weights) == 86
        assert len(model.src_dst_opt._states()) == 86

        generated = _synthetic_batch(model, batch=1)
        samples = ((generated[0], generated[1], generated[2]),
                   (generated[3], generated[4], generated[5]))
        calls = []
        model.generate_next_samples = lambda: calls.append("fetch") or samples
        seen = []
        real_train = model.src_dst_train
        model.src_dst_train = lambda *args: seen.append(args) or (1.0, 2.0)
        # Iteration zero is divisible by three, but there is no previous batch
        # yet: it must acquire fresh samples and use the warped inputs.
        model.set_iter(0)
        assert dict(model.onTrainOneIter()) == {"src_loss": 1.0,
                                                "dst_loss": 2.0}
        assert calls == ["fetch"]
        assert seen[-1][0] is generated[0]
        assert seen[-1][3] is generated[3]

        # A later every-third iteration does have previous samples and must
        # reuse that batch while substituting its unwarped targets.
        model.set_iter(3)
        model.onTrainOneIter()
        assert calls == ["fetch"]
        assert seen[-1][0] is generated[1]
        assert seen[-1][3] is generated[4]
        model.src_dst_train = real_train

        counter = [0]
        monkeypatch.setattr(
            nn, "random_binomial",
            lambda shape, p, dtype, device=None: _controlled_dropout(
                shape, p, dtype, device, counter=counter))
        batch = _synthetic_batch(model, batch=1)
        model._src_dst_train_vectors(*batch)
        assert int(model.src_dst_opt.iterations) == 1
        model.set_iter(7)
        view_before = model.AE_view(batch[1], batch[4])
        state_before = [value.detach().clone()
                        for value in model.src_dst_opt.get_weights()]
        model.save()
        expected_files = {
            "encoder.npy", "inter.npy", "decoder_src.npy",
            "decoder_dst.npy", "src_dst_opt.npy", "data.dat"}
        assert (root / "test_Quick96_data.dat").is_file()
        assert expected_files == {
            path.name.removeprefix("test_Quick96_")
            for path in root.glob("test_Quick96_*.npy")
        } | {"data.dat"}

        counter[:] = [0]
        model._src_dst_train_vectors(*batch)
        uninterrupted = [
            _tensor_digest(value)
            for value in (model.src_dst_trainable_weights
                          + model.src_dst_opt.get_weights())]
    finally:
        model.finalize()

    resumed = _make_model(root)
    try:
        assert resumed._quick96_saved_model_resume is True
        assert resumed.get_iter() == 7
        assert int(resumed.src_dst_opt.iterations) == 1
        for actual, expected in zip(resumed.src_dst_opt.get_weights(),
                                    state_before):
            assert torch.equal(actual, expected)
        for actual, expected in zip(resumed.AE_view(batch[1], batch[4]),
                                    view_before):
            np.testing.assert_array_equal(actual, expected)
        counter[:] = [0]
        resumed._src_dst_train_vectors(*batch)
        resumed_digests = [
            _tensor_digest(value)
            for value in (resumed.src_dst_trainable_weights
                          + resumed.src_dst_opt.get_weights())]
        assert resumed_digests == uninterrupted
    finally:
        resumed.finalize()

    opt_path = root / "test_Quick96_src_dst_opt.npy"
    backup = root / "missing-opt-backup.npy"
    opt_path.replace(backup)
    try:
        with pytest.raises(FileNotFoundError, match="src_dst_opt.npy"):
            broken = _make_model(root)
            broken.finalize()
    finally:
        backup.replace(opt_path)


def test_historical_three_file_pretrained_initialization(plain_tmp):
    source_root = Path(plain_tmp) / "source"
    source = _make_model(source_root)
    try:
        source.set_iter(1)
        source.save()
        expected = {
            name: [p.detach().clone() for p in component.get_weights()]
            for name, component in (
                ("encoder.npy", source.encoder),
                ("decoder_src.npy", source.decoder_src),
                ("decoder_dst.npy", source.decoder_dst))}
    finally:
        source.finalize()

    pretrained = Path(plain_tmp) / "historical_pretrained"
    pretrained.mkdir()
    for filename in expected:
        src = source_root / f"test_Quick96_{filename}"
        dst = pretrained / filename
        try:
            os.link(src, dst)
        except OSError:
            shutil.copyfile(src, dst)
    assert {p.name for p in pretrained.iterdir()} == {
        "encoder.npy", "decoder_src.npy", "decoder_dst.npy"}

    target_root = Path(plain_tmp) / "target"
    target = _make_model(target_root, pretrained_model_path=pretrained)
    try:
        assert target._quick96_saved_model_resume is False
        assert target.pretrained_components_loaded == [
            "encoder.npy", "decoder_src.npy", "decoder_dst.npy"]
        for filename, component in (
                ("encoder.npy", target.encoder),
                ("decoder_src.npy", target.decoder_src),
                ("decoder_dst.npy", target.decoder_dst)):
            for actual, wanted in zip(component.get_weights(),
                                      expected[filename]):
                assert torch.equal(actual, wanted)
        assert int(target.src_dst_opt.iterations) == 0
        assert all(torch.count_nonzero(state) == 0
                   for state in target.src_dst_opt._states())
        assert not (pretrained / "inter.npy").exists()
        assert not (pretrained / "src_dst_opt.npy").exists()
        assert not (pretrained / "data.dat").exists()
    finally:
        target.finalize()

    corrupt_root = Path(plain_tmp) / "corrupt_target"
    corrupt = Path(plain_tmp) / "corrupt_pretrained"
    shutil.copytree(pretrained, corrupt)
    payload = pickle.loads((corrupt / "encoder.npy").read_bytes())
